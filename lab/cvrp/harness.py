# ---------------------------------------------------------------- the judge
def nint(value: float) -> int:
    """CVRPLIB rounding: nearest integer, halves rounded up."""
    return int(math.floor(value + 0.5))


def distance_matrix(coords: list[list[int]]) -> np.ndarray:
    """Rounded Euclidean distances between every pair of nodes."""
    xy = np.asarray(coords, dtype=np.float64)
    diff = xy[:, None, :] - xy[None, :, :]
    return np.floor(np.sqrt((diff ** 2).sum(axis=2)) + 0.5).astype(np.int64)


def check_solution(instance: dict, routes: object) -> int:
    """Validate *routes* for *instance* and return their cost (the judge)."""
    if not isinstance(routes, (list, tuple)):
        raise HarnessError(f"solve() must return a list of routes, got {type(routes).__name__}")
    clean: list[list[int]] = []
    for route in routes:
        if not isinstance(route, (list, tuple)):
            raise HarnessError("each route must be a list of customer numbers")
        nodes = []
        for v in route:
            if isinstance(v, bool) or not isinstance(v, (int, np.integer)):
                raise HarnessError(f"customer numbers must be integers, got {v!r}")
            nodes.append(int(v))
        if nodes:
            clean.append(nodes)
    n = instance["customers"]
    visited = [v for r in clean for v in r]
    if len(visited) != n or sorted(visited) != list(range(1, n + 1)):
        missing = n - len(set(visited) & set(range(1, n + 1)))
        extra = len([v for v in visited if not 1 <= v <= n])
        dupes = len(visited) - len(set(visited))
        raise HarnessError(f"routes must visit customers 1..{n} exactly once "
                           f"({missing} missing, {extra} out of range, {dupes} repeated)")
    demands = instance["demands"]
    for route in clean:
        load = sum(demands[v] for v in route)
        if load > instance["capacity"]:
            raise HarnessError(f"a route carries {load}, over the capacity {instance['capacity']}")
    coords = instance["coords"]
    total = 0
    for route in clean:
        previous = 0
        for node in route + [0]:
            (x1, y1), (x2, y2) = coords[previous], coords[node]
            total += nint(math.hypot(x1 - x2, y1 - y2))
            previous = node
    return total


def gap_pct(cost: int, bks: int) -> float:
    """Percentage gap of *cost* above the best-known solution."""
    return round(100.0 * (cost - bks) / bks, 4)


# ---------------------------------------------------------------- baseline: savings
def savings_routes(instance: dict) -> list[list[int]]:
    """Clarke and Wright (1964) parallel savings, then 2-opt inside each route.

    The textbook construction heuristic, used as the simple-rule baseline.
    """
    d = distance_matrix(instance["coords"])
    demands = instance["demands"]
    capacity = instance["capacity"]
    n = instance["customers"]
    route_of = list(range(n + 1))                # customer -> route id
    routes = {i: [i] for i in range(1, n + 1)}
    loads = {i: demands[i] for i in range(1, n + 1)}
    i_idx, j_idx = np.triu_indices(n, k=1)
    i_idx, j_idx = i_idx + 1, j_idx + 1
    saving = d[0, i_idx] + d[0, j_idx] - d[i_idx, j_idx]
    order = np.lexsort((j_idx, i_idx, -saving))
    for k in order:
        if saving[k] <= 0:
            break
        a, b = int(i_idx[k]), int(j_idx[k])
        ra, rb = route_of[a], route_of[b]
        if ra == rb or loads[ra] + loads[rb] > capacity:
            continue
        A, B = routes[ra], routes[rb]
        if A[-1] == a and B[0] == b:
            merged = A + B
        elif A[0] == a and B[-1] == b:
            merged = B + A
        elif A[0] == a and B[0] == b:
            merged = A[::-1] + B
        elif A[-1] == a and B[-1] == b:
            merged = A + B[::-1]
        else:
            continue                             # a or b is interior
        routes[ra] = merged
        loads[ra] += loads[rb]
        del routes[rb], loads[rb]
        for v in B:
            route_of[v] = ra
    return [two_opt(r, d) for r in routes.values()]


def two_opt(route: list[int], d: np.ndarray) -> list[int]:
    """First-improvement 2-opt on one route (depot at both ends)."""
    tour = [0] + route + [0]
    improved = True
    while improved:
        improved = False
        for i in range(1, len(tour) - 2):
            for j in range(i + 1, len(tour) - 1):
                delta = (d[tour[i - 1], tour[j]] + d[tour[i], tour[j + 1]]
                         - d[tour[i - 1], tour[i]] - d[tour[j], tour[j + 1]])
                if delta < 0:
                    tour[i:j + 1] = tour[i:j + 1][::-1]
                    improved = True
    return tour[1:-1]


# ---------------------------------------------------------------- static check
def docstring_nodes(tree: ast.AST) -> set[int]:
    """ids of the Constant nodes that are docstrings."""
    found = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            body = getattr(node, "body", [])
            if (body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant)
                    and isinstance(body[0].value.value, str)):
                found.add(id(body[0].value))
    return found


def static_check(path: Path) -> list[str]:
    """Return the reasons an experiment file is refused (empty if it is fine).

    An allowlist, read from the parsed code: only the listed modules may be
    imported; nothing that opens files, inspects the interpreter or reaches
    around the harness may be named; and the file may not carry large tables
    of numbers or text (which could smuggle in routes computed elsewhere).
    """
    raw = path.read_bytes()
    problems: list[str] = []
    if len(raw) > MAX_EXPERIMENT_BYTES:
        problems.append(f"file is {len(raw)} bytes (limit {MAX_EXPERIMENT_BYTES})")
    try:
        tree = ast.parse(raw.decode("utf-8"))
    except (SyntaxError, UnicodeDecodeError) as exc:
        return problems + [f"does not parse: {exc}"]
    docs = docstring_nodes(tree)
    numbers = 0
    string_chars = 0
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.split(".")[0] not in ALLOWED_IMPORTS:
                    problems.append(f"import {alias.name}")
        elif isinstance(node, ast.ImportFrom):
            if node.level or (node.module or "").split(".")[0] not in ALLOWED_IMPORTS:
                problems.append(f"from {'.' * node.level}{node.module or ''} import")
            for alias in node.names:
                if alias.name in BANNED_NAMES or alias.name in BANNED_ATTRIBUTES or alias.name.startswith("__"):
                    problems.append(f"import of {alias.name}")
        elif isinstance(node, ast.Name):
            if node.id in BANNED_NAMES or (node.id.startswith("__") and node.id != "__name__"):
                problems.append(f"name {node.id}")
        elif isinstance(node, ast.Attribute):
            if node.attr in BANNED_ATTRIBUTES or node.attr.startswith("__"):
                problems.append(f"attribute .{node.attr}")
        elif isinstance(node, (ast.List, ast.Tuple, ast.Set)):
            if len(node.elts) > MAX_LITERAL_ELEMENTS:
                problems.append(f"a literal with {len(node.elts)} elements (limit {MAX_LITERAL_ELEMENTS})")
        elif isinstance(node, ast.Dict):
            if len(node.keys) > MAX_LITERAL_ELEMENTS:
                problems.append(f"a dict literal with {len(node.keys)} entries (limit {MAX_LITERAL_ELEMENTS})")
        elif isinstance(node, ast.Constant):
            if isinstance(node.value, (int, float, complex)) and not isinstance(node.value, bool):
                numbers += 1
            elif isinstance(node.value, (str, bytes)) and id(node) not in docs:
                string_chars += len(node.value)
    if numbers > MAX_NUMERIC_CONSTANTS:
        problems.append(f"{numbers} numeric constants (limit {MAX_NUMERIC_CONSTANTS})")
    if string_chars > MAX_STRING_CHARS:
        problems.append(f"{string_chars} characters of string constants (limit {MAX_STRING_CHARS})")
    return sorted(set(problems))


# ---------------------------------------------------------------- running a solver
def children_cpu() -> float:
    """CPU seconds used so far by finished child processes (0 where unmeasurable)."""
    if resource is None:
        return 0.0
    usage = resource.getrusage(resource.RUSAGE_CHILDREN)
    return usage.ru_utime + usage.ru_stime


def kill_group(proc: subprocess.Popen) -> None:
    """Kill the runner and anything it started."""
    if proc.poll() is None or os.name == "posix":
        try:
            if os.name == "posix":
                os.killpg(proc.pid, signal.SIGKILL)
            else:  # pragma: no cover - Windows
                proc.kill()
        except (ProcessLookupError, PermissionError, OSError):
            pass
    try:
        proc.wait(10)
    except subprocess.TimeoutExpired:  # pragma: no cover
        pass


def run_one(path: Path, instance: dict, seed: int) -> dict:
    """Solve one instance under the rules; return cost, gap and timings."""
    limit = time_limit(instance)
    token = secrets.token_hex(16)
    message = json.dumps({"token": token, "seed": seed, "time_limit": limit,
                          "capacity": instance["capacity"], "coords": instance["coords"],
                          "demands": instance["demands"]}).encode("utf-8")
    env = {**os.environ, "OMP_NUM_THREADS": "1", "OPENBLAS_NUM_THREADS": "1",
           "MKL_NUM_THREADS": "1", "NUMEXPR_NUM_THREADS": "1", "PYTHONHASHSEED": "0"}
    lines: queue.Queue = queue.Queue()
    prefix = token.encode("ascii") + b" "
    with tempfile.TemporaryDirectory() as tmp:
        with open(Path(tmp) / "stderr.txt", "w+b") as stderr:
            cpu_before = children_cpu()
            extra = {"start_new_session": True} if os.name == "posix" else {}
            proc = subprocess.Popen([sys.executable, "-E", str(RUNNER), str(path.resolve())],
                                    stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=stderr,
                                    cwd=tmp, env=env, **extra)

            def reader() -> None:
                assert proc.stdout is not None
                for raw in proc.stdout:
                    if raw.startswith(prefix):
                        kind, _, payload = raw[len(prefix):].decode("utf-8", "replace").partition(" ")
                        lines.put((time.monotonic(), kind.strip(), payload))
                lines.put((time.monotonic(), "EOF", ""))

            threading.Thread(target=reader, daemon=True).start()
            try:
                assert proc.stdin is not None
                proc.stdin.write(message)
                proc.stdin.close()
                ready_at = wait_for(lines, ("READY",), READY_TIMEOUT_S, instance["name"], stderr)
                deadline = limit * TIME_FACTOR + TIME_GRACE_S + KILL_EXTRA_S
                done_at, payload = wait_for(lines, ("RESULT",), deadline, instance["name"], stderr,
                                            with_payload=True)
            finally:
                kill_group(proc)
            cpu = children_cpu() - cpu_before
    elapsed = done_at - ready_at
    if elapsed > limit * TIME_FACTOR + TIME_GRACE_S:
        raise HarnessError(f"{instance['name']}: solve() answered after {elapsed:.2f} s, over its "
                           f"{limit} s limit (allowed {limit * TIME_FACTOR + TIME_GRACE_S:.2f} s).")
    if resource is not None and cpu > limit * CPU_FACTOR + CPU_GRACE_S:
        raise HarnessError(f"{instance['name']}: used {cpu:.1f} CPU seconds for a {limit} s limit; "
                           "experiments must use one core.")
    try:
        routes = json.loads(payload)
    except ValueError as exc:
        raise HarnessError(f"{instance['name']}: the answer could not be read ({exc}).") from exc
    cost = check_solution(instance, routes)
    return {"instance": instance["name"], "customers": instance["customers"], "seed": seed,
            "time_limit": limit, "cost": cost, "bks": instance["bks"],
            "gap_pct": gap_pct(cost, instance["bks"]), "routes": len([r for r in routes if r]),
            "solve_seconds": round(elapsed, 2), "cpu_seconds": round(cpu, 2), "solution": routes}


def wait_for(lines: queue.Queue, kinds: tuple[str, ...], timeout: float, name: str, stderr,
             with_payload: bool = False):
    """Wait for a protocol line of one of *kinds*; explain anything else."""
    end = time.monotonic() + timeout
    while True:
        remaining = end - time.monotonic()
        if remaining <= 0:
            raise HarnessError(f"{name}: no answer within {timeout:.1f} s; the run was stopped.")
        try:
            stamp, kind, payload = lines.get(timeout=remaining)
        except queue.Empty:
            continue
        if kind in kinds:
            return (stamp, payload) if with_payload else stamp
        if kind == "ERROR":
            try:
                detail = json.loads(payload)
            except ValueError:
                detail = payload
            raise HarnessError(f"{name}: solve() raised an error:\n{detail}")
        if kind == "EOF":
            stderr.seek(0)
            tail = stderr.read()[-1500:].decode("utf-8", "replace")
            raise HarnessError(f"{name}: the solver process ended without an answer.\n{tail}")


def run_set(path: Path, names: list[str], instances: dict[str, dict], seeds: list[int]) -> list[dict]:
    """Run *path* on every instance in *names* for every seed (caller holds the lock)."""
    results = []
    for seed in seeds:
        for name in names:
            result = run_one(path, instances[name], seed)
            results.append(result)
            print(f"  {name:14s} seed {seed}  cost {result['cost']:>8d}  "
                  f"gap {result['gap_pct']:6.3f}%  ({result['solve_seconds']} s)", flush=True)
    return results


@contextlib.contextmanager
def solver_lock():
    """Run one timed evaluation at a time, so parallel trials never share the CPU.

    The time limit is wall-clock time, so two solvers running at once would
    each get less computing and score worse. Other evaluations wait here.
    Budget checks and ledger writes also happen under this lock.
    """
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    if fcntl is None:  # Windows: a local check only; the lab itself runs on Linux.
        yield
        return
    with open(LOCK, "w") as handle:
        try:
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            print("Another evaluation is running; waiting for it to finish ...", flush=True)
            fcntl.flock(handle, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)


def summarize(results: list[dict], reference: dict[tuple[str, int], int] | None = None) -> dict:
    """Mean, median and worst gap; how many instances beat the reference cost."""
    if not results:
        raise HarnessError("no instances were run")
    gaps = [r["gap_pct"] for r in results]
    out = {
        "instances": len(results),
        "mean_gap_pct": round(statistics.fmean(gaps), 4),
        "median_gap_pct": round(statistics.median(gaps), 4),
        "worst_gap_pct": round(max(gaps), 4),
        "seconds": round(sum(r["solve_seconds"] for r in results), 1),
        "cpu_seconds": round(sum(r["cpu_seconds"] for r in results), 1),
    }
    if reference:
        compared = [r for r in results if (r["instance"], r["seed"]) in reference]
        wins = sum(1 for r in compared if r["cost"] < reference[(r["instance"], r["seed"])])
        if compared:
            out["beats_reference"] = f"{wins}/{len(compared)}"
    return out


# ---------------------------------------------------------------- ledger
def git_commit() -> str:
    """Return the short git commit of the repository, or '' if unavailable."""
    try:
        out = subprocess.run(["git", "-C", str(REPO_ROOT), "rev-parse", "--short", "HEAD"],
                             capture_output=True, text=True, timeout=10)
        return out.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return ""


def read_ledger() -> list[dict[str, str]]:
    """Return the ledger rows (empty if there is no ledger yet)."""
    if not LEDGER.exists():
        return []
    with open(LEDGER, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def append_ledger(row: dict[str, object]) -> None:
    """Append one row to the ledger, writing the header the first time."""
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    new = not LEDGER.exists()
    with open(LEDGER, "a", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=LEDGER_FIELDS, delimiter="\t", extrasaction="ignore")
        if new:
            writer.writeheader()
        writer.writerow({k: str(row.get(k, "")).replace("\t", " ").replace("\n", " ")
                         for k in LEDGER_FIELDS})


def save_details(row: dict, results: list[dict]) -> None:
    """Keep every instance's result and routes, so any number can be re-checked."""
    DETAILS_DIR.mkdir(parents=True, exist_ok=True)
    stem = (f"{row['utc'].replace(':', '')}_{row['kind']}_{Path(str(row['experiment'])).stem}"
            f"_{row.get('experiment_sha12') or 'none'}_{uuid.uuid4().hex[:8]}")
    with open(DETAILS_DIR / f"{stem}.json", "x", encoding="utf-8") as handle:
        handle.write(json.dumps({"row": row, "results": results}) + "\n")


def relative(path: Path) -> str:
    """Show *path* relative to the repository root when possible."""
    try:
        return str(path.resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def base_row(kind: str, split: str, path: Path | None, seeds: list[int], note: str) -> dict:
    """Fields shared by every ledger row."""
    prints = fingerprint()
    return {
        "utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "kind": kind, "split": split,
        "experiment": relative(path) if path else "savings (in harness)",
        "experiment_sha12": sha256_file(path)[:12] if path else "",
        "git_commit": git_commit(), "seeds": ",".join(map(str, seeds)),
        "harness_sha12": prints["harness"][:12], "snapshot_sha12": prints["snapshot"][:12],
        "note": note,
    }


def reference_costs(split: str) -> dict[tuple[str, int], int]:
    """Costs of the frozen reference per (instance, seed), from saved details."""
    costs: dict[tuple[str, int], int] = {}
    if not DETAILS_DIR.exists():
        return costs
    reference_path = relative(REFERENCE)
    reference_sha = sha256_file(REFERENCE)[:12]
    for path in sorted(DETAILS_DIR.glob("*.json")):
        record = json.loads(path.read_text(encoding="utf-8"))
        row = record["row"]
        if (row.get("split") == split and row.get("kind") in ("baseline", "final_reference")
                and row.get("experiment") == reference_path
                and row.get("experiment_sha12") == reference_sha and row.get("status") == "ok"):
            for r in record["results"]:
                costs[(r["instance"], r["seed"])] = r["cost"]
    return costs


def started(kind: str) -> int:
    """How many val evaluations of *kind* this ledger has started (the budget count)."""
    return sum(1 for r in read_ledger()
               if r["kind"] == kind and r["split"] == "val" and r["status"] == "started")


def evaluate(path: Path, split: str, kind: str, seeds: list[int], note: str,
             names: list[str] | None = None, budget: int | None = None) -> tuple[dict, list[dict]]:
    """Run an experiment on a split under the lock and record it in the ledger."""
    if not path.exists():
        raise HarnessError(f"No experiment file at {path}")
    problems = static_check(path)
    if problems:
        row = base_row(kind, split, path, seeds, note)
        row.update(status="refused", note=f"{note} | refused: {'; '.join(problems)}"[:500])
        with solver_lock():
            append_ledger(row)
        raise HarnessError("The experiment is refused: " + "; ".join(problems) + ". Experiments may "
                           "import only " + ", ".join(sorted(ALLOWED_IMPORTS)) + ", must not open "
                           "files or inspect the interpreter, and must not carry large tables.")
    instances = load_instances()
    names = names or split_names(instances, split)
    if not names:
        raise HarnessError("no instances to run")
    with solver_lock():
        if budget is not None and started(kind) >= budget:
            raise HarnessError(f"The {kind} budget of {budget} is used up.")
        row = base_row(kind, split, path, seeds, note)
        append_ledger({**row, "status": "started"})
        try:
            results = run_set(path, names, instances, seeds)
        except HarnessError as exc:
            row.update(status="invalid", note=f"{note} | {exc}"[:500])
            append_ledger(row)
            raise
        row.update(summarize(results, reference_costs(split)))
        row["status"] = "ok"
        append_ledger(row)
        save_details(row, results)
    return row, results


def savings_on(split: str) -> tuple[dict, list[dict]]:
    """Score the savings baseline on a split (deterministic, no time limit needed)."""
    instances = load_instances()
    results = []
    for name in split_names(instances, split):
        started_at = time.time()
        routes = savings_routes(instances[name])
        cost = check_solution(instances[name], routes)
        results.append({"instance": name, "customers": instances[name]["customers"], "seed": 0,
                        "cost": cost, "bks": instances[name]["bks"],
                        "gap_pct": gap_pct(cost, instances[name]["bks"]), "routes": len(routes),
                        "solve_seconds": round(time.time() - started_at, 2), "cpu_seconds": 0.0,
                        "solution": routes})
    return summarize(results), results


def parse_seeds(text: str) -> list[int]:
    """Parse a comma-separated list of seeds."""
    try:
        seeds = [int(s) for s in text.split(",") if s.strip()]
    except ValueError as exc:
        raise HarnessError(f"seeds must be whole numbers separated by commas, got {text!r}") from exc
    if not seeds or len(seeds) != len(set(seeds)) or any(s < 0 for s in seeds):
        raise HarnessError(f"give one or more distinct, non-negative seeds, got {text!r}")
    return seeds


