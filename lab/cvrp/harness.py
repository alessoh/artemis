def cmd_recheck(args: argparse.Namespace) -> int:
    """Re-run on val with seeds 1 and 2, for the Skeptic (and the reference, once, if needed)."""
    path = Path(args.experiment).resolve()
    sha = sha256_file(path)[:12]
    evaluated = any(r["kind"] == "experiment" and r["split"] == "val" and r["status"] == "ok"
                    and r["experiment_sha12"] == sha for r in read_ledger())
    if not evaluated:
        raise HarnessError("Recheck only a file that `evaluate` has already scored (same contents).")
    seeds = list(RECHECK_SEEDS)
    instances = load_instances()
    ref = reference_costs("val")
    if not all((n, s) in ref for n in split_names(instances, "val") for s in seeds):
        print("Running the frozen reference on the recheck seeds first (once per ledger, not counted):")
        evaluate(REFERENCE, "val", "baseline", seeds, "reference pyvrp_default on recheck seeds")
    row, _ = evaluate(path, "val", "recheck", seeds, args.note or "", budget=RECHECK_BUDGET)
    row["rechecks_used"] = started("recheck")
    print("RECHECK " + json.dumps(row))
    return 0


def paired_stats(experiment: list[dict], reference: list[dict]) -> dict:
    """Paired comparison of the experiment with the reference on the same problems and seeds.

    For each problem the gap is averaged over the seeds, then d = experiment gap
    minus reference gap (percentage points; negative means the experiment is
    better). Reported: mean d with a 95 percent bootstrap interval over problems
    (fixed random seed, so the numbers are reproducible), problems won and lost,
    an exact two-sided sign test on those wins and losses, and the head-to-head
    count over every (problem, seed) pair.
    """
    ref = {(r["instance"], r["seed"]): r for r in reference}
    per_problem: dict[str, list[float]] = {}
    pair_wins = pair_losses = pair_ties = 0
    for r in experiment:
        other = ref.get((r["instance"], r["seed"]))
        if other is None:
            continue
        per_problem.setdefault(r["instance"], []).append(r["gap_pct"] - other["gap_pct"])
        pair_wins += r["cost"] < other["cost"]
        pair_losses += r["cost"] > other["cost"]
        pair_ties += r["cost"] == other["cost"]
    diffs = np.array([statistics.fmean(v) for v in per_problem.values()])
    if not len(diffs):
        raise HarnessError("no paired results to compare")
    rng = np.random.default_rng(0)
    boots = rng.choice(diffs, size=(BOOTSTRAP_DRAWS, len(diffs)), replace=True).mean(axis=1)
    wins, losses = int((diffs < 0).sum()), int((diffs > 0).sum())
    n = wins + losses
    tail = sum(math.comb(n, k) for k in range(0, min(wins, losses) + 1)) / 2 ** n if n else 1.0
    return {
        "problems": len(diffs),
        "seeds": sorted({r["seed"] for r in experiment}),
        "mean_difference_pct_points": round(float(diffs.mean()), 4),
        "ci95_low": round(float(np.percentile(boots, 2.5)), 4),
        "ci95_high": round(float(np.percentile(boots, 97.5)), 4),
        "problems_won": wins, "problems_lost": losses, "problems_tied": len(diffs) - n,
        "sign_test_p_two_sided": round(min(1.0, 2 * tail), 5),
        "pairs_won": pair_wins, "pairs_lost": pair_losses, "pairs_tied": pair_ties,
    }


def cmd_final(args: argparse.Namespace) -> int:
    path = Path(args.experiment).resolve()
    if path != DEFAULT_EXPERIMENT.resolve():
        raise HarnessError("`final` scores lab/cvrp/experiment.py, the promoted solver, and nothing else.")
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    try:
        # Created before anything runs: an interrupted final still counts as used.
        with open(FINAL_STARTED, "x", encoding="utf-8") as handle:
            handle.write(json.dumps({"utc": datetime.now(timezone.utc).isoformat(),
                                     "experiment_sha256": sha256_file(path)}) + "\n")
    except FileExistsError:
        raise HarnessError(f"The held-out splits were already used ({relative(FINAL_STARTED)}). "
                           "The final score is reported once; it is never re-run to get a "
                           "better number.") from None
    result: dict[str, object] = {"fingerprint": fingerprint(),
                                 "experiment_sha256": sha256_file(path),
                                 "definitions": {"seconds_per_100_customers": SECONDS_PER_100_CUSTOMERS,
                                                 "seeds": list(FINAL_SEEDS)}}
    seeds = list(FINAL_SEEDS)
    pooled_exp: list[dict] = []
    pooled_ref: list[dict] = []
    for split in ("test", "scale"):
        print(f"Reference (PyVRP default) on {split}, seeds {seeds}:")
        ref_row, ref_results = evaluate(REFERENCE, split, "final_reference", seeds,
                                        f"final reference on {split}")
        print(f"Experiment on {split}, seeds {seeds}:")
        exp_row, exp_results = evaluate(path, split, "final", seeds, args.note or f"final on {split}")
        savings, _ = savings_on(split)
        result[split] = {"experiment": exp_row, "pyvrp_default": ref_row, "savings": savings,
                         "paired_vs_pyvrp_default": paired_stats(exp_results, ref_results)}
        pooled_exp += exp_results
        pooled_ref += ref_results
    result["test_and_scale_pooled"] = {"paired_vs_pyvrp_default": paired_stats(pooled_exp, pooled_ref)}
    FINAL_RESULT.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print("FINAL " + json.dumps(result))
    return 0


def parse_solution_file(path: Path) -> list[list[int]]:
    """Read a CVRPLIB-format solution file ("Route #1: 3 7 9 ...")."""
    routes = []
    for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        line = raw.strip()
        if line.lower().startswith("route"):
            try:
                routes.append([int(x) for x in line.partition(":")[2].split()])
            except ValueError as exc:
                raise HarnessError(f"{path.name} line {number}: {exc}") from exc
    if not routes:
        raise HarnessError(f"{path} contains no 'Route #k:' lines")
    return routes


def cmd_verify(args: argparse.Namespace) -> int:
    """Check a solution file and compare it with the snapshot's BKS."""
    instances = load_instances()
    if args.instance not in instances:
        raise HarnessError(f"Unknown instance {args.instance}")
    instance = instances[args.instance]
    if instance["split"] in ("val", "test", "scale") and not final_done():
        raise HarnessError(f"{args.instance} is in the {instance['split']} split; verify it only after `final`.")
    path = Path(args.solution).resolve()
    cost = check_solution(instance, parse_solution_file(path))
    verdict = ("BEATS the best-known solution in the snapshot" if cost < instance["bks"]
               else "equals the best-known solution" if cost == instance["bks"]
               else "is above the best-known solution")
    out = {"instance": args.instance, "cost": cost, "bks_in_snapshot": instance["bks"],
           "gap_pct": gap_pct(cost, instance["bks"]), "verdict": verdict,
           "solution_sha12": sha256_file(path)[:12], "solution_file": relative(path)}
    with solver_lock():
        new = not RECORDS.exists()
        with open(RECORDS, "a", encoding="utf-8", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=["utc", *out.keys()], delimiter="\t")
            if new:
                writer.writeheader()
            writer.writerow({"utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), **out})
    print("VERIFY " + json.dumps(out))
    if cost < instance["bks"]:
        print("A possible new record. Before claiming it, check the current CVRPLIB table "
              "(galgos.inf.puc-rio.br/cvrplib), because the snapshot's BKS may be out of date.")
    return 0


