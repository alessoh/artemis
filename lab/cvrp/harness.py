# ---------------------------------------------------------------- integrity
def sha256_file(path: Path) -> str:
    """Return the hex SHA-256 of the file at *path*."""
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def fingerprint() -> dict[str, str]:
    """Return the SHA-256 of the harness, runner, reference solver and snapshot."""
    return {
        "harness": sha256_file(Path(__file__).resolve()),
        "runner": sha256_file(RUNNER),
        "reference": sha256_file(REFERENCE),
        "snapshot": sha256_file(SNAPSHOT) if SNAPSHOT.exists() else "missing",
    }


def load_instances() -> dict[str, dict]:
    """Load the frozen snapshot after checking it against its manifest."""
    if not SNAPSHOT.exists() or not MANIFEST.exists():
        raise HarnessError("The data snapshot is missing. A human builds it once with "
                           "`python lab/cvrp/prepare_data.py` and commits lab/cvrp/data/.")
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    actual = sha256_file(SNAPSHOT)
    if actual != manifest.get("sha256"):
        raise HarnessError(f"The snapshot does not match its manifest (expected "
                           f"{str(manifest.get('sha256'))[:12]}, found {actual[:12]}). "
                           "Someone changed the data; restore it from git before continuing.")
    with gzip.open(SNAPSHOT, "rt", encoding="utf-8") as handle:
        payload = json.load(handle)
    return {i["name"]: i for i in payload["instances"]}


