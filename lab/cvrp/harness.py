"""Artemis routing harness: the frozen half of the AutoResearch contract.

DO NOT EDIT THIS FILE. Agents edit experiment.py (or a copy of it in trials/);
humans change this file, and every change shows up in its fingerprint.

The question
------------
Given the same short time limit on one CPU core, can the lab's agents build a
capacitated vehicle routing (CVRP) solver that gets closer to the best-known
solutions of the CVRPLIB X benchmark than PyVRP's default solver, a
state-of-the-art open-source library? And, in longer runs, can any of its
routes beat a published best-known solution outright?

The judge
---------
The harness, not the experiment, checks every solution and computes its
length. A solution is a list of routes; each route is a list of customer
numbers 1..n, and the depot (0) is implied at both ends. It is valid only if
every customer is visited exactly once and no route carries more than the
vehicle capacity. Its cost is the sum of Euclidean distances rounded to the
nearest integer, the CVRPLIB convention; prepare_data.py re-computed all 100
published best-known costs with this code and matched every one exactly.

Each solve() runs in its own process (runner.py, also frozen), in a new
process group, from an empty folder, with one BLAS thread. The harness itself
measures the time from "ready" to the answer and the CPU the process used.

Pre-registered definitions (fixed 2026-10-07 by Claude, owner Peter Alesso)
---------------------------------------------------------------------------
Time limit:     3.0 seconds per 100 customers (e.g. 13.44 s for 448 customers),
                one CPU core. The answer must arrive within 1.03 x the limit
                plus 0.5 s of the runner reporting ready.
Primary metric: mean gap to the best-known solution over the val instances,
                gap = 100 * (cost - BKS) / BKS, seed 0. Lower is better.
Final test:     test and scale, seeds 0, 1 and 2, for the experiment and the
                frozen reference; reported with a paired comparison (mean
                difference, 95 percent bootstrap interval, sign test).
Also reported:  median and worst gap, and on how many instances the
                experiment beat the frozen PyVRP reference (same seed).
Splits:         see prepare_data.py. "train" and "hunt" may be probed freely;
                "val" is the loop's pool (60 evaluations and 20 rechecks per
                run); "test" and "scale" are used exactly once, by `final`.
Records:        `verify` checks a solution file and reports whether it beats
                the BKS in the frozen snapshot (val, test and scale instances
                only after `final`).

Commands
--------
    python lab/cvrp/harness.py fingerprint
    python lab/cvrp/harness.py describe
    python lab/cvrp/harness.py baselines
    python lab/cvrp/harness.py probe --experiment lab/cvrp/trials/NAME.py --instances X-n101-k25,X-n120-k6
    python lab/cvrp/harness.py evaluate --experiment lab/cvrp/trials/NAME.py --note "..."
    python lab/cvrp/harness.py recheck --experiment lab/cvrp/trials/NAME.py
    python lab/cvrp/harness.py final            # once, at the very end
    python lab/cvrp/harness.py verify --instance X-n801-k40 --solution path/to/file.sol

Every evaluation writes a "started" row to the ledger before it runs and a
result row ("ok" or "invalid") after; budgets count the started rows, so an
interrupted evaluation still counts.
"""

