"""Frozen runner: executes one experiment's choose() on every dataset of a split.

DO NOT EDIT THIS FILE. It is part of the harness fingerprint.

The harness starts this script with `python -E` (PYTHON* variables ignored),
in a new process group, from an empty temporary folder, with a minimal
environment. It reads one JSON message on stdin: a one-time token, the seed,
the paths of the null tables and of the precomputed clustering cache, and the
unlabelled datasets (the points only; labels never reach this process). It
loads the tables and the cache, imports the frozen kit, NumPy, SciPy and
scikit-learn, installs an audit hook, imports the experiment from the copy
the harness checked, and prints "<token> READY". For each dataset it calls
choose(X, kit, seed) and prints "<token> CHOICE <json>"; at the end
"<token> DONE". The harness, not this process, measures the time.

After the hook is installed the process may open files only for reading and
only inside the Python installation, the lab's own code folder or the
experiment's copy; it may not start processes, open network connections or
change the hook.
"""

import importlib.util
import json
import math
import os
import random
import sys
import time
import traceback
from pathlib import Path

import numpy as np

PREIMPORT = ("scipy", "scipy.stats", "scipy.special", "scipy.optimize", "scipy.sparse",
             "scipy.linalg", "scipy.spatial", "scipy.cluster", "scipy.cluster.hierarchy",
             "sklearn", "sklearn.linear_model", "sklearn.preprocessing", "sklearn.metrics",
             "sklearn.neighbors", "sklearn.decomposition", "sklearn.cluster", "sklearn.mixture")
DENIED_EVENTS = ("subprocess.Popen", "os.system", "os.exec", "os.posix_spawn", "os.spawn",
                 "os.fork", "os.forkpty", "pty.spawn", "socket.", "urllib.", "http.",
                 "ftplib.", "smtplib.", "webbrowser.", "sys.addaudithook", "os.remove",
                 "os.unlink", "os.rename", "os.rmdir", "os.mkdir", "os.chmod", "os.putenv",
                 "os.unsetenv", "shutil.")


def install_guard(experiment_path, lab_dir):
    roots = {os.path.normcase(os.path.realpath(p)) for p in
             (sys.prefix, sys.base_prefix, sys.exec_prefix, sys.base_exec_prefix,
              os.path.dirname(np.__file__), os.path.dirname(os.path.dirname(np.__file__)))}
    code_files = {os.path.normcase(os.path.realpath(os.path.join(lab_dir, f)))
                  for f in ("kit.py", "unccd.py", "nulls.py")}
    allowed_file = os.path.normcase(os.path.realpath(experiment_path))

    def inside(path):
        real = os.path.normcase(os.path.realpath(path))
        if real == allowed_file or real in code_files:
            return True
        for root in roots:
            try:
                if os.path.commonpath([real, root]) == root:
                    return True
            except ValueError:
                continue
        return False

    def hook(event, args):
        if event == "open":
            path, mode, flags = (list(args) + [None, None, None])[:3]
            if isinstance(path, int):
                return
            if isinstance(path, bytes):
                path = os.fsdecode(path)
            writing = (isinstance(mode, str) and any(c in mode for c in "wax+")) or (
                isinstance(flags, int) and flags & (os.O_WRONLY | os.O_RDWR | os.O_CREAT))
            if writing or not inside(str(path)):
                raise PermissionError(f"the experiment may not open {path!r}")
        elif event.startswith(DENIED_EVENTS):
            raise PermissionError(f"the experiment may not use {event}")

    sys.addaudithook(hook)


def load_cache(path):
    """{dataset index: {(alpha, direction): result}} from the precomputed cache."""
    if not path:
        return {}
    z = np.load(path)
    alphas = [float(a) for a in z["alphas"]]
    directions = [str(d) for d in z["directions"]]
    out = {}
    for i in range(int(z["count"])):
        labels, radii = z[f"labels{i}"], z[f"radii{i}"]
        si, balls = z[f"si{i}"], z[f"balls{i}"]
        entry = {}
        for a_i, a in enumerate(alphas):
            for d_i, d in enumerate(directions):
                lab = labels[a_i, d_i].astype(int)
                entry[(a, d)] = {"labels": lab, "silhouette": float(si[a_i, d_i]),
                                 "balls": int(balls[a_i, d_i]),
                                 "clusters": int(len(np.unique(lab))),
                                 "radii": radii[a_i, d_i].astype(float)}
        out[i] = entry
    return out


def main():
    here = str(Path(__file__).resolve().parent)
    sys.path[:] = [p for p in sys.path if p not in ("", ".", here)]
    sys.dont_write_bytecode = True
    message = json.loads(sys.stdin.read())
    token = message["token"]
    # The protocol goes to a private copy of stdout; anything the experiment
    # prints (to sys.stdout or file descriptor 1) goes to stderr instead.
    out = os.fdopen(os.dup(1), "w")
    os.dup2(2, 1)
    sys.stdout = sys.stderr

    def emit(kind, payload=""):
        out.write(f"{token} {kind} {payload}\n")
        out.flush()

    try:
        seed = int(message["seed"])
        datasets = message["datasets"]
        tables = {}
        for d, path in message["tables"].items():
            z = np.load(path)
            tables[int(d)] = {"alphas": z["alphas"].copy(), "ave": z["ave"].copy(), "med": z["med"].copy()}
        cache = load_cache(message.get("cache"))
        del message
        for name in PREIMPORT:
            importlib.import_module(name)
        # the frozen kit and the code it uses, from the lab's folder, before the guard
        for name in ("nulls", "unccd", "kit"):
            spec = importlib.util.spec_from_file_location(name, os.path.join(here, f"{name}.py"))
            module = importlib.util.module_from_spec(spec)
            sys.modules[name] = module
            spec.loader.exec_module(module)
        Kit = sys.modules["kit"].Kit
        snap = sys.modules["nulls"].snap
        random.seed(seed)
        np.random.seed(seed)
        spec = importlib.util.spec_from_file_location("artemis_experiment", sys.argv[1])
        module = importlib.util.module_from_spec(spec)
        install_guard(sys.argv[1], here)
        spec.loader.exec_module(module)
        if not hasattr(module, "choose"):
            raise RuntimeError("the experiment must define choose(X, kit, seed)")
        emit("READY")
        for i, item in enumerate(datasets):
            X = np.asarray(item["X"], dtype=np.float64)
            kit = Kit(X, tables[X.shape[1]], cache.get(item.get("cache_index")))
            t0 = time.process_time()
            answer = module.choose(X.copy(), kit, seed)
            cpu = time.process_time() - t0
            if isinstance(answer, dict):
                alpha, direction = answer.get("alpha"), answer.get("direction", "ascend")
            elif isinstance(answer, (tuple, list)):
                alpha, direction = answer[0], (answer[1] if len(answer) > 1 else "ascend")
            else:
                alpha, direction = answer, "ascend"
            if isinstance(alpha, bool) or not isinstance(alpha, (int, float, np.integer, np.floating)):
                raise ValueError(f"choose() returned a non-numeric alpha {alpha!r} for dataset {i}")
            alpha = float(alpha)
            if not math.isfinite(alpha) or alpha <= 0:
                raise ValueError(f"choose() returned alpha {alpha!r} for dataset {i}")
            if direction not in ("ascend", "descend"):
                raise ValueError(f"choose() returned direction {direction!r} for dataset {i}")
            emit("CHOICE", json.dumps({"i": i, "alpha_raw": alpha, "alpha": snap(alpha),
                                       "direction": direction, "cpu": round(cpu, 3)}))
        emit("DONE")
    except BaseException:  # noqa: BLE001
        emit("ERROR", json.dumps(traceback.format_exc(limit=6)))


if __name__ == "__main__":
    main()
