def _constant_only(node: ast.AST) -> bool:
    """True for a literal number or arithmetic made only of literal numbers."""
    if isinstance(node, ast.Constant):
        return isinstance(node.value, (int, float)) and not isinstance(node.value, bool)
    if isinstance(node, ast.UnaryOp):
        return _constant_only(node.operand)
    if isinstance(node, ast.BinOp):
        return _constant_only(node.left) and _constant_only(node.right)
    return False


def formula_constants(tree: ast.AST) -> int:
    """Numeric constants in a formula: each literal other than 0, 1, 2 (and their negatives),
    and each piece of arithmetic made only of literals, counts once."""
    count = 0
    counted: set[int] = set()

    def visit(node: ast.AST, inside: bool) -> None:
        nonlocal count
        if not inside and isinstance(node, (ast.BinOp, ast.UnaryOp)) and _constant_only(node):
            is_free = (isinstance(node, ast.UnaryOp) and isinstance(node.operand, ast.Constant)
                       and node.operand.value in FORMULA_FREE)
            if not is_free:
                count += 1
            for child in ast.walk(node):
                counted.add(id(child))
            return
        if isinstance(node, ast.Constant) and id(node) not in counted:
            v = node.value
            if isinstance(v, (int, float)) and not isinstance(v, bool) and v not in FORMULA_FREE:
                count += 1
        for child in ast.iter_child_nodes(node):
            visit(child, inside)

    visit(tree, False)
    return count


def _is_listed_submodule_violation(module: str, name: str) -> bool:
    """True when `from module import name` names a submodule that is not on the allowlist."""
    top = module.split(".")[0]
    if top not in ALLOWED_SUBMODULES or "." in module:
        return False
    if name in ALLOWED_SUBMODULES[top]:
        return False
    try:
        import importlib.util
        return importlib.util.find_spec(f"{module}.{name}") is not None
    except (ImportError, ValueError, AttributeError):
        return False


