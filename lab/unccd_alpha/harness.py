    """The reasons a file is refused (empty if it is fine); see program.md."""
    problems: list[str] = []
    if len(raw) > MAX_EXPERIMENT_BYTES:
        problems.append(f"file is {len(raw)} bytes (limit {MAX_EXPERIMENT_BYTES})")
    try:
        tree = ast.parse(raw.decode("utf-8"))
    except (SyntaxError, UnicodeDecodeError, ValueError) as exc:
        return problems + [f"does not parse: {exc}"]
    docs = docstring_nodes(tree)
    banned = BANNED_NAMES | BANNED_ATTRIBUTES
    numbers, formula_numbers, string_chars = 0, 0, 0
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if not module_allowed(alias.name):
                    problems.append(f"import {alias.name}")
        elif isinstance(node, ast.ImportFrom):
            if node.level or not module_allowed(node.module or ""):
                problems.append(f"from {'.' * node.level}{node.module or ''} import")
            for alias in node.names:
                if alias.name == "*":
                    problems.append("import *")
                elif alias.name in banned or alias.name.startswith("_"):
                    problems.append(f"import of {alias.name}")
                elif node.module and _is_listed_submodule_violation(node.module, alias.name):
                    problems.append(f"from {node.module} import {alias.name} (a submodule not on the list)")
        elif isinstance(node, ast.Name):
            if node.id in banned or (node.id.startswith("__") and node.id != "__name__"):
                problems.append(f"name {node.id}")
        elif isinstance(node, ast.Attribute):
            if node.attr in BANNED_ATTRIBUTES or node.attr.startswith("_"):
                problems.append(f"attribute .{node.attr}")
        elif isinstance(node, (ast.List, ast.Tuple, ast.Set)):
            if len(node.elts) > MAX_LITERAL_ELEMENTS:
                problems.append(f"a literal with {len(node.elts)} elements (limit {MAX_LITERAL_ELEMENTS})")
        elif isinstance(node, ast.Dict):
            if len(node.keys) > MAX_LITERAL_ELEMENTS:
                problems.append(f"a dict literal with {len(node.keys)} entries (limit {MAX_LITERAL_ELEMENTS})")
        elif isinstance(node, ast.Constant):
            value = node.value
            if isinstance(value, (int, float, complex)) and not isinstance(value, bool):
                numbers += 1
                if value not in FORMULA_FREE:
                    formula_numbers += 1
                if isinstance(value, int) and abs(value) > MAX_INT_MAGNITUDE:
                    problems.append("an integer constant larger than 2**63")
            elif isinstance(value, bytes):
                problems.append("a bytes constant")
            elif isinstance(value, str) and id(node) not in docs:
                string_chars += len(value)
                if len(value) > MAX_STRING_CONSTANT:
                    problems.append(f"a string constant of {len(value)} characters (limit {MAX_STRING_CONSTANT})")
                if "__" in value:
                    problems.append("a string containing a double underscore")
    if numbers > MAX_NUMERIC_CONSTANTS:
        problems.append(f"{numbers} numeric constants (limit {MAX_NUMERIC_CONSTANTS})")
    if string_chars > MAX_STRING_CHARS:
        problems.append(f"{string_chars} characters of string constants (limit {MAX_STRING_CHARS})")
    if formula:
        formula_numbers = formula_constants(tree)
        if formula_numbers > MAX_FORMULA_CONSTANTS:
            problems.append(f"{formula_numbers} numeric constants other than 0, 1 and 2 "
                            f"(a formula may have at most {MAX_FORMULA_CONSTANTS})")
        assigned = {t.id for node in ast.walk(tree) if isinstance(node, (ast.Assign, ast.AnnAssign, ast.AugAssign))
                    for t in ast.walk(node) if isinstance(t, ast.Name) and isinstance(t.ctx, ast.Store)}
        for node in ast.walk(tree):
            if isinstance(node, FORMULA_BANNED_NODES):
                problems.append(f"a formula may not use {type(node).__name__} (closed-form expressions only)")
            elif isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load) and node.id not in FORMULA_NAMES | assigned:
                problems.append(f"a formula may not use the name {node.id}")
            elif isinstance(node, ast.Attribute) and node.attr in MATH_CONSTANTS:
                problems.append(f"a formula may not use math.{node.attr} (it counts as a hidden constant)")
            elif (isinstance(node, ast.Constant) and isinstance(node.value, str) and id(node) not in docs
                  and node.value not in ("ascend", "descend")):
                problems.append("a formula may contain no strings other than \"ascend\" and \"descend\"")
        funcs = [n for n in tree.body if isinstance(n, ast.FunctionDef)]
        if [f.name for f in funcs] != ["alpha_formula"] or [a.arg for a in funcs[0].args.args] != ["n", "d"]:
            problems.append("a formula file must define exactly one function, alpha_formula(n, d)")
        for node in ast.walk(tree):
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                names = [a.name for a in node.names] if isinstance(node, ast.Import) else [node.module or ""]
                if any(nm.split(".")[0] != "math" for nm in names):
                    problems.append("a formula may import only math")
    return sorted(set(problems))


