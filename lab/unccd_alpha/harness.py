def table_for(d: int) -> dict:
    path = NULL_DIR / f"nn_d{d}.npz"
    if not path.exists():
        raise HarnessError(f"no null table for dimension {d}")
    z = np.load(path)
    return {"alphas": z["alphas"], "ave": z["ave"], "med": z["med"], "path": str(path)}


class Cache:
    """Precomputed clusterings for every dataset of a split, alpha and direction (no labels)."""

    def __init__(self, path: Path):
        z = np.load(path)
        self.path = path
        self.alphas = [float(a) for a in z["alphas"]]
        self.directions = [str(d) for d in z["directions"]]
        self.labels = [z[f"labels{i}"] for i in range(int(z["count"]))]

    def labels_for(self, i: int, alpha: float, direction: str) -> np.ndarray:
        a = self.alphas.index(nulls.snap(alpha))
        return self.labels[i][a, self.directions.index(direction)].astype(int)


def build_cache(split: str, shard: tuple[int, int] = (0, 1)) -> None:
    """Cluster every dataset of a split at every alpha choice in both directions (humans).

    shard (k, m) computes only the datasets whose index is k modulo m, so that m
    processes can share the work; the last one to finish writes the cache file.
    """
    for name, data_path, cache_path in split_paths(split):
        data = load_split(data_path)
        count = len(data["X"])
        partial = HERE / "work" / "cache_partial" / name
        partial.mkdir(parents=True, exist_ok=True)
        t0 = time.time()
        for i, X in enumerate(data["X"]):
            out_file = partial / f"{i}.npz"
            if out_file.exists() or i % shard[1] != shard[0]:
                continue
            if not (NULL_DIR / f"nn_d{X.shape[1]}.npz").exists():
                print(f"[cache {name}] {i + 1}/{count}: no null table for d={X.shape[1]} yet; skipped", flush=True)
                continue
            table = table_for(X.shape[1])
            n = len(X)
            labels = np.zeros((len(nulls.CHOICES), 2, n), dtype=np.int32)
            radii = np.zeros((len(nulls.CHOICES), 2, n))
            si = np.zeros((len(nulls.CHOICES), 2))
            balls = np.zeros((len(nulls.CHOICES), 2), dtype=np.int32)
            ddx = unccd.distance_matrix(X)
            for a_i, a in enumerate(nulls.CHOICES):
                row = nulls.level_index(table["alphas"], a)
                for d_i, direction in enumerate(DIRECTIONS):
                    out = unccd.cluster(X, table["ave"][row], table["med"][row], direction, ddx)
                    labels[a_i, d_i] = out["labels"]
                    radii[a_i, d_i] = out["radii"]
                    si[a_i, d_i] = out["si"]
                    balls[a_i, d_i] = out["si_ind"]
            tmp = partial / f"{i}.tmp.npz"
            np.savez_compressed(tmp, labels=labels, radii=radii, si=si, balls=balls)
            tmp.rename(out_file)
            print(f"[cache {name}] {i + 1}/{count} n={n} d={X.shape[1]} ({time.time() - t0:.0f}s)", flush=True)
        if not all((partial / f"{i}.npz").exists() for i in range(count)):
            print(f"[cache {name}] incomplete; run build-cache again when every null table exists")
            continue
        arrays = {"alphas": np.asarray(nulls.CHOICES), "directions": np.asarray(DIRECTIONS), "count": count}
        for i in range(count):
            z = np.load(partial / f"{i}.npz")
            for key in ("labels", "radii", "si", "balls"):
                arrays[f"{key}{i}"] = z[key]
        np.savez_compressed(cache_path, **arrays)
        print(f"wrote {cache_path}")


# ---------------------------------------------------------------- scoring
def ari(a, b) -> float:
    """Adjusted Rand index (Hubert and Arabie), as mclust::adjustedRandIndex."""
    a = np.unique(np.asarray(a), return_inverse=True)[1].ravel()
    b = np.unique(np.asarray(b), return_inverse=True)[1].ravel()
    n = len(a)
    if n < 2:
        return 0.0
    table = np.zeros((a.max() + 1, b.max() + 1))
    np.add.at(table, (a, b), 1)
    comb = lambda x: x * (x - 1) / 2.0  # noqa: E731
    s_ij = comb(table).sum()
    s_a = comb(table.sum(axis=1)).sum()
    s_b = comb(table.sum(axis=0)).sum()
    expected = s_a * s_b / comb(n)
    maximum = (s_a + s_b) / 2.0
    if maximum == expected:
        return 1.0
    return float((s_ij - expected) / (maximum - expected))


def dataset_ari(labels: np.ndarray, y: np.ndarray) -> float:
    keep = y >= 0
    return ari(labels[keep], y[keep])


def regime_keys(meta: list[dict], part: str) -> list[str]:
    if part == "test_real":
        return [f"real:{m['name']}" for m in meta]
    return [f"{part}:{m['regime']}" for m in meta]


def summarise(per_dataset: list[float], keys: list[str], seed: int = 0) -> dict:
    """Mean over regimes of the mean ARI of each regime's datasets, with a bootstrap interval."""
    by: dict[str, list[float]] = {}
    for k, v in zip(keys, per_dataset):
        by.setdefault(k, []).append(v)
    names = sorted(by)
    scores = np.array([np.mean(by[k]) for k in names])
    rng = np.random.default_rng(seed)
    draws = scores[rng.integers(0, len(scores), (BOOTSTRAP_DRAWS, len(scores)))].mean(axis=1)
    return {"mean_ari": float(scores.mean()), "ci95_low": float(np.quantile(draws, 0.025)),
            "ci95_high": float(np.quantile(draws, 0.975)), "regimes": len(names),
            "datasets": len(per_dataset), "regime_names": names, "regime_scores": scores.tolist()}


def paired(a: dict, b: dict, seed: int = 0) -> dict:
    """Paired bootstrap over regimes of (a - b)."""
    if a["regime_names"] != b["regime_names"]:
        raise HarnessError("the two results cover different regimes")
    diff = np.asarray(a["regime_scores"]) - np.asarray(b["regime_scores"])
    rng = np.random.default_rng(seed)
    draws = diff[rng.integers(0, len(diff), (BOOTSTRAP_DRAWS, len(diff)))].mean(axis=1)
    return {"delta": float(diff.mean()), "delta_ci95_low": float(np.quantile(draws, 0.025)),
            "delta_ci95_high": float(np.quantile(draws, 0.975))}


def score_choices(split: str, choices: dict[str, list[dict]]) -> tuple[dict, list[dict]]:
    """ARI of each dataset under the chosen settings, and the split summary."""
    per, keys, rows = [], [], []
    for part, data_path, cache_path in split_paths(split):
        data = load_split(data_path)
        cache = Cache(cache_path) if cache_path.exists() else None
        for i, (X, y) in enumerate(zip(data["X"], data["y"])):
            ch = choices[part][i]
            if cache is not None:
                labels = cache.labels_for(i, ch["alpha"], ch["direction"])
            else:
                t = table_for(X.shape[1])
                row = nulls.level_index(t["alphas"], ch["alpha"])
                labels = unccd.cluster(X, t["ave"][row], t["med"][row], ch["direction"])["labels"]
            value = dataset_ari(labels, y)
            per.append(value)
            rows.append({"part": part, "i": i, "alpha": ch["alpha"], "direction": ch["direction"],
                         "ari": value, **{k: data["meta"][i].get(k) for k in ("dist", "d", "n", "k", "noise", "name")}})
        keys += regime_keys(data["meta"], part)
    return summarise(per, keys), rows


# ---------------------------------------------------------------- baselines (computed here)
def schedule_alpha(d: int) -> tuple[float, str]:
    """The paper's schedule; log-linear in d between the listed dimensions, then snapped."""
    ds = sorted(PAPER_SCHEDULE)
    if d in PAPER_SCHEDULE:
        a = PAPER_SCHEDULE[d]
    elif d < ds[0]:
        a = PAPER_SCHEDULE[ds[0]]
    elif d > ds[-1]:
        a = PAPER_SCHEDULE[ds[-1]]
    else:
        lo = max(x for x in ds if x < d)
        hi = min(x for x in ds if x > d)
        t = (d - lo) / (hi - lo)
        a = math.exp((1 - t) * math.log(PAPER_SCHEDULE[lo]) + t * math.log(PAPER_SCHEDULE[hi]))
    return nulls.snap(a), ("descend" if d >= 10 else "ascend")


def baseline_choices(split: str, rule: str) -> dict[str, list[dict]]:
    out = {}
    for part, data_path, cache_path in split_paths(split):
        data = load_split(data_path)
        cache = np.load(cache_path) if cache_path.exists() else None
        lst = []
        for i, (X, y) in enumerate(zip(data["X"], data["y"])):
            d = X.shape[1]
            if rule == "paper_schedule":
                a, direction = schedule_alpha(d)
            elif rule.startswith("fixed_"):
                a, direction = float(rule.split("_")[1]), "ascend"
            elif rule == "silhouette_max":
                si = cache[f"si{i}"][:, 0]
                a, direction = nulls.CHOICES[int(np.argmax(si))], "ascend"
            elif rule in ("oracle_ascend", "oracle_any"):
                labels = cache[f"labels{i}"]
                best, best_v = None, -np.inf
                dirs = (0,) if rule == "oracle_ascend" else (0, 1)
                for a_i, a_ in enumerate(nulls.CHOICES):
                    for d_i in dirs:
                        v = dataset_ari(labels[a_i, d_i].astype(int), y)
                        if v > best_v:
                            best, best_v = (a_, DIRECTIONS[d_i]), v
                a, direction = best
            else:
                raise HarnessError(f"unknown baseline {rule}")
            lst.append({"alpha": nulls.snap(a), "direction": direction})
        out[part] = lst
    return out


