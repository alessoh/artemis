def cmd_final(_: argparse.Namespace) -> None:
    """Score the frozen experiment, formula and baselines on the sealed test split (humans, once)."""
    check_data()
    if final_done():
        raise HarnessError("The final test has already been run.")
    for _, data_path, cache_path in split_paths("test"):
        if not data_path.exists() or not cache_path.exists():
            raise HarnessError("The sealed test split is built by the humans after the lab finishes "
                               "(prepare_data.py test, then build-cache --split test). It is not in the sandbox.")
    if not FROZEN.exists():
        raise HarnessError("runs/unccd_alpha/frozen.json is missing; the lab's last step, `freeze`, records "
                           "which files the final test scores.")
    frozen = json.loads(FROZEN.read_text(encoding="utf-8"))
    for path, key, is_formula in ((DEFAULT_EXPERIMENT, "experiment_sha256", False),
                                  (DEFAULT_FORMULA, "formula_sha256", True)):
        if sha256_file(path) != frozen.get(key):
            raise HarnessError(f"{path.name} is not the file the lab froze (frozen.json {key}).")
        problems = static_check_source(path.read_bytes(), formula=is_formula)
        if problems:
            raise HarnessError(f"{path.name} is refused: {'; '.join(problems)}")
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    FINAL_STARTED.write_text(datetime.now(timezone.utc).isoformat() + "\n")
    try:
        _final_body()
    except BaseException as exc:
        FINAL_RESULT.write_text(json.dumps({"status": "failed", "error": repr(exc)[:2000],
                                            "utc": datetime.now(timezone.utc).isoformat()}, indent=2) + "\n")
        raise


def _final_body() -> None:
    results: dict = {"status": "ok", "fingerprint": fingerprint(), "git_commit": git_commit(),
                     "experiment_sha256": sha256_file(DEFAULT_EXPERIMENT), "formula_sha256": sha256_file(DEFAULT_FORMULA)}
    per_part: dict[str, dict] = {}
    for label, path, is_formula in (("experiment", DEFAULT_EXPERIMENT, False), ("formula", DEFAULT_FORMULA, True)):
        source = path.read_bytes() + (FORMULA_SHIM if is_formula else b"")
        choices, seconds, cpu = run_experiment(source, "test", SEED)
        per_part[label] = choices
        results.setdefault("seconds", {})[label] = seconds
    for rule in BASELINE_RULES:
        per_part[rule] = baseline_choices("test", rule)
    summaries = {}
    for label, choices in per_part.items():
        syn = {"test_synthetic": choices["test_synthetic"]}
        real = {"test_real": choices["test_real"]}
        s_syn, rows_syn = _score_part("test_synthetic", syn)
        s_real, rows_real = _score_part("test_real", real)
        summaries[label] = {"synthetic": s_syn, "real": s_real, "rows": rows_syn + rows_real,
                            "alphas_used": alphas_used(choices)}
    def pair(a, b, part="synthetic"):
        return paired(summaries[a][part], summaries[b][part])
    h1 = pair("experiment", "paper_schedule")
    h2 = pair("formula", "experiment")
    results["H1"] = {**h1, "margin": -NONINFERIORITY, "holds": h1["delta_ci95_low"] > -NONINFERIORITY}
    results["H2"] = {**h2, "margin": -NONINFERIORITY, "holds": h2["delta_ci95_low"] > -NONINFERIORITY}
    results["secondary"] = {f"{a}_minus_{b}": pair(a, b) for a, b in (
        ("experiment", "fixed_0.01"), ("experiment", "silhouette_max"), ("experiment", "oracle_any"),
        ("formula", "paper_schedule"), ("paper_schedule", "fixed_0.01"))}
    results["summaries"] = {k: {"synthetic": {kk: v["synthetic"][kk] for kk in ("mean_ari", "ci95_low", "ci95_high", "regimes", "datasets")},
                                "real_mean_ari": v["real"]["mean_ari"],
                                "real_by_dataset": dict(zip(v["real"]["regime_names"], v["real"]["regime_scores"])),
                                "alphas_used": v["alphas_used"]} for k, v in summaries.items()}
    results["rows"] = {k: v["rows"] for k, v in summaries.items()}
    FINAL_RESULT.write_text(json.dumps(results, indent=2) + "\n")
    print(json.dumps({k: results[k] for k in ("H1", "H2", "secondary")}, indent=2))
    for k, v in results["summaries"].items():
        print(f"{k:<16} synthetic {v['synthetic']['mean_ari']:.4f} [{v['synthetic']['ci95_low']:.4f}, "
              f"{v['synthetic']['ci95_high']:.4f}]  real {v['real_mean_ari']:.4f}")


def _score_part(part: str, choices: dict) -> tuple[dict, list[dict]]:
    name_map = {p: (dp, cp) for p, dp, cp in split_paths("test")}
    data_path, cache_path = name_map[part]
    data = load_split(data_path)
    cache = Cache(cache_path)
    per, rows = [], []
    for i, (X, y) in enumerate(zip(data["X"], data["y"])):
        ch = choices[part][i]
        value = dataset_ari(cache.labels_for(i, ch["alpha"], ch["direction"]), y)
        per.append(value)
        rows.append({"part": part, "i": i, "alpha": ch["alpha"], "direction": ch["direction"], "ari": value,
                     **{k: data["meta"][i].get(k) for k in ("dist", "d", "n", "k", "noise", "name")}})
    return summarise(per, regime_keys(data["meta"], part)), rows


