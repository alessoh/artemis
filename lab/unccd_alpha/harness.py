# ---------------------------------------------------------------- running an experiment
def children_cpu() -> float:
    if resource is None:
        return 0.0
    usage = resource.getrusage(resource.RUSAGE_CHILDREN)
    return usage.ru_utime + usage.ru_stime


def kill_group(proc: subprocess.Popen) -> None:
    try:
        if os.name == "posix":
            os.killpg(proc.pid, signal.SIGKILL)
        else:  # pragma: no cover
            proc.kill()
    except (ProcessLookupError, PermissionError, OSError):
        pass
    try:
        proc.wait(10)
    except subprocess.TimeoutExpired:  # pragma: no cover
        pass


MEMORY_LIMIT_BYTES = 6 * 1024 ** 3


def _limit_memory() -> None:  # runs in the child before exec (POSIX only)
    if resource is not None:
        resource.setrlimit(resource.RLIMIT_AS, (MEMORY_LIMIT_BYTES, MEMORY_LIMIT_BYTES))


def runner_env() -> dict[str, str]:
    env = {"OMP_NUM_THREADS": "1", "OPENBLAS_NUM_THREADS": "1", "MKL_NUM_THREADS": "1",
           "NUMEXPR_NUM_THREADS": "1", "PYTHONHASHSEED": "0", "LOKY_MAX_CPU_COUNT": "1"}
    for name in ("PATH", "SYSTEMROOT", "WINDIR", "TEMP", "TMP", "TMPDIR", "LANG", "LC_ALL"):
        if name in os.environ:
            env[name] = os.environ[name]
    return env


def run_experiment(source: bytes, split: str, seed: int) -> tuple[dict[str, list[dict]], float, float]:
    """Run choose() from *source* on every dataset of *split*, one process per part of the split."""
    choices: dict[str, list[dict]] = {}
    total_seconds, total_cpu = 0.0, 0.0
    for part, data_path, cache_path in split_paths(split):
        data = load_split(data_path)
        cache_arg = str(cache_path) if cache_path.exists() else None
        datasets, tables = [], {}
        for i, X in enumerate(data["X"]):
            datasets.append({"X": X.tolist(), "cache_index": i if cache_arg else None})
            tables[str(X.shape[1])] = table_for(X.shape[1])["path"]
        answers, seconds, cpu = _run_runner(source, datasets, tables, cache_arg, seed, TIME_LIMIT_S[split])
        choices[part] = answers
        total_seconds += seconds
        total_cpu += cpu
    return choices, round(total_seconds, 1), round(total_cpu, 1)


def _run_runner(source: bytes, datasets: list[dict], tables: dict, cache: str | None, seed: int,
                time_limit: float) -> tuple[list[dict], float, float]:
    token = secrets.token_hex(16)
    message = json.dumps({"token": token, "seed": seed, "datasets": datasets, "tables": tables,
                          "cache": cache}, separators=(",", ":")).encode("utf-8")
    lines: queue.Queue = queue.Queue()
    prefix = token.encode("ascii") + b" "
    answers: list[dict] = []
    with tempfile.TemporaryDirectory() as tmp:
        code_path = Path(tmp) / "experiment_under_test.py"
        code_path.write_bytes(source)
        with open(Path(tmp) / "stderr.txt", "w+b") as stderr:
            cpu_before = children_cpu()
            extra = {"start_new_session": True, "preexec_fn": _limit_memory} if os.name == "posix" else {}
            started_at = time.monotonic()
            proc = subprocess.Popen([sys.executable, "-E", str(RUNNER), str(code_path)],
                                    stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=stderr,
                                    cwd=tmp, env=runner_env(), **extra)

            def reader() -> None:
                assert proc.stdout is not None
                for raw in proc.stdout:
                    if raw.startswith(prefix):
                        kind, _, payload = raw[len(prefix):].decode("utf-8", "replace").partition(" ")
                        lines.put((time.monotonic(), kind.strip(), payload))
                lines.put((time.monotonic(), "EOF", ""))

            def writer() -> None:
                try:
                    assert proc.stdin is not None
                    proc.stdin.write(message)
                    proc.stdin.close()
                except (BrokenPipeError, OSError):
                    pass

            threading.Thread(target=reader, daemon=True).start()
            threading.Thread(target=writer, daemon=True).start()
            ready_at = None
            try:
                deadline = time.monotonic() + READY_TIMEOUT_S
                while True:
                    remaining = deadline - time.monotonic()
                    if remaining <= 0:
                        if ready_at is None:
                            raise HarnessError("the experiment did not start in time; the run was stopped.")
                        raise HarnessError(f"the experiment did not finish within {time_limit:.0f} s; "
                                           "the run was stopped.")
                    try:
                        stamp, kind, payload = lines.get(timeout=remaining)
                    except queue.Empty:
                        continue
                    if kind == "READY" and ready_at is None:
                        ready_at = stamp
                        deadline = stamp + time_limit
                    elif kind == "CHOICE":
                        answers.append(json.loads(payload))
                    elif kind == "DONE":
                        done_at = stamp
                        break
                    elif kind == "ERROR":
                        try:
                            detail = json.loads(payload)
                        except ValueError:
                            detail = payload
                        raise HarnessError(f"choose() raised an error:\n{detail}")
                    elif kind == "EOF":
                        stderr.seek(0)
                        tail = stderr.read()[-1500:].decode("utf-8", "replace")
                        raise HarnessError(f"the experiment process ended without finishing.\n{tail}")
                if ready_at is None:
                    raise HarnessError("the experiment never reported READY.")
            finally:
                kill_group(proc)
            cpu = children_cpu() - cpu_before
    wall = done_at - started_at
    if resource is not None and cpu > CPU_FACTOR * wall + CPU_GRACE_S:
        raise HarnessError(f"used {cpu:.0f} CPU seconds in {wall:.0f} s of wall time; experiments must use one core.")
    if len(answers) != len(datasets) or [a["i"] for a in answers] != list(range(len(datasets))):
        raise HarnessError("the experiment did not answer every dataset in order.")
    return ([{"alpha": float(a["alpha"]), "direction": a["direction"], "alpha_raw": a["alpha_raw"]} for a in answers],
            round(done_at - ready_at, 1), round(cpu, 1))


@contextlib.contextmanager
def eval_lock():
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    if fcntl is None:
        yield
        return
    with open(LOCK, "w") as handle:
        try:
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            print("Another evaluation is running; waiting for it to finish ...", flush=True)
            fcntl.flock(handle, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)


# ---------------------------------------------------------------- ledger
def git_commit() -> str:
    try:
        out = subprocess.run(["git", "-C", str(REPO_ROOT), "rev-parse", "--short", "HEAD"],
                             capture_output=True, text=True, timeout=10)
        return out.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return ""


def read_ledger() -> list[dict[str, str]]:
    if not LEDGER.exists():
        return []
    with open(LEDGER, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def append_ledger(row: dict[str, object]) -> None:
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    new = not LEDGER.exists()
    with open(LEDGER, "a", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=LEDGER_FIELDS, delimiter="\t", extrasaction="ignore")
        if new:
            writer.writeheader()
        writer.writerow({k: str(row.get(k, "")).replace("\t", " ").replace("\n", " ") for k in LEDGER_FIELDS})


def relative(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def base_row(kind: str, split: str, label: str, sha12: str, seeds: list[int], note: str) -> dict:
    prints = fingerprint()
    return {"utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "kind": kind, "split": split,
            "experiment": label, "experiment_sha12": sha12, "git_commit": git_commit(),
            "seeds": ",".join(map(str, seeds)), "harness_sha12": prints["harness"][:12],
            "data_sha12": prints["data"][:12], "note": note}


def save_details(row: dict, summary: dict, rows: list[dict], source: bytes | None) -> None:
    DETAILS_DIR.mkdir(parents=True, exist_ok=True)
    stem = (f"{row['utc'].replace(':', '')}_{row['kind']}_{row['split']}_{Path(str(row['experiment'])).stem}"
            f"_{row.get('experiment_sha12') or 'none'}_s{row['seeds']}_{uuid.uuid4().hex[:8]}")
    record = {"row": row, "summary": summary, "datasets": rows}
    if source is not None:
        (DETAILS_DIR / f"{stem}.code.txt").write_bytes(source)
        record["code_file"] = f"{stem}.code.txt"
    with open(DETAILS_DIR / f"{stem}.json", "x", encoding="utf-8") as handle:
        handle.write(json.dumps(record) + "\n")


def saved_summary(split: str, sha12: str, seed: int, kinds=("experiment", "recheck")) -> dict | None:
    if not DETAILS_DIR.exists():
        return None
    found = None
    for path in sorted(DETAILS_DIR.glob("*.json")):
        record = json.loads(path.read_text(encoding="utf-8"))
        row = record["row"]
        if (row.get("split") == split and row.get("experiment_sha12") == sha12 and row.get("seeds") == str(seed)
                and row.get("status") == "ok" and row.get("kind") in kinds):
            found = record["summary"]
    return found


def started(kind: str) -> int:
    return sum(1 for r in read_ledger() if r["kind"] == kind and r["split"] == "val" and r["status"] == "started")


def alphas_used(choices: dict[str, list[dict]]) -> str:
    counts: dict[str, int] = {}
    for lst in choices.values():
        for c in lst:
            key = f"{c['alpha']:g}{'d' if c['direction'] == 'descend' else ''}"
            counts[key] = counts.get(key, 0) + 1
    return " ".join(f"{k}:{v}" for k, v in sorted(counts.items(), key=lambda kv: -kv[1]))


def refuse_if_bad(path: Path, kind: str, split: str, seeds: list[int], note: str, formula: bool = False) -> bytes:
    if not path.exists():
        raise HarnessError(f"No file at {path}")
    source = path.read_bytes()
    problems = static_check_source(source, formula=formula)
    if problems:
        row = base_row(kind, split, relative(path), hashlib.sha256(source).hexdigest()[:12], seeds, note)
        row.update(status="refused", note=f"{note} | refused: {'; '.join(problems)}"[:500])
        with eval_lock():
            append_ledger(row)
        raise HarnessError("Refused: " + "; ".join(problems) + ". See the rules in program.md.")
    return source + FORMULA_SHIM if formula else source


def evaluate(path: Path, kind: str, split: str, seed: int, note: str, budget: int | None = None,
             formula: bool = False, best_path: Path | None = None) -> tuple[dict, dict, list[dict]]:
    source = refuse_if_bad(path, kind, split, [seed], note, formula)
    sha12 = hashlib.sha256(source).hexdigest()[:12]
    with eval_lock():
        if budget is not None and started(kind) >= budget:
            raise HarnessError(f"The {kind} budget of {budget} is used up.")
        row = base_row(kind, split, relative(path), sha12, [seed], note)
        if split == "val":
            append_ledger({**row, "status": "started"})
        try:
            choices, seconds, cpu = run_experiment(source, split, seed)
        except HarnessError as exc:
            row.update(status="invalid", note=f"{note} | {exc}"[:500])
            append_ledger(row)
            raise
        summary, rows = score_choices(split, choices)
        row.update({k: summary[k] for k in ("mean_ari", "ci95_low", "ci95_high", "regimes", "datasets")},
                   seconds=seconds, cpu_seconds=cpu, status="ok", alphas_used=alphas_used(choices))
        best_path = best_path or (DEFAULT_FORMULA if formula else DEFAULT_EXPERIMENT)
        if split == "val" and best_path.exists():
            best_src = best_path.read_bytes() + (FORMULA_SHIM if formula else b"")
            best_sha = hashlib.sha256(best_src).hexdigest()[:12]
            if best_sha != sha12:
                kinds = ("formula",) if formula else ("experiment", "recheck")
                best = saved_summary("val", best_sha, seed, kinds=kinds)
                if best is None and seed != SEED:
                    # a deterministic incumbent gives the same result on every seed
                    best = saved_summary("val", best_sha, SEED, kinds=kinds)
                    if best is not None:
                        row["note"] = f"{note} | incumbent compared at seed {SEED}"
                if best is None:
                    print("NOTE: no saved val result for the current best file, so no paired comparison "
                          "(evaluate the current best first).", flush=True)
                if best is not None:
                    d = paired(summary, best)
                    row.update(delta_vs_best=d["delta"], delta_ci95_low=d["delta_ci95_low"],
                               delta_ci95_high=d["delta_ci95_high"])
        append_ledger(row)
        if split in ("val", "test"):
            save_details(row, summary, rows, source)
    return row, summary, rows


