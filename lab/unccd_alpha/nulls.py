"""Monte Carlo null tables for the UN-CCD randomness test, on a grid of alpha.

DO NOT EDIT THIS FILE. It is part of the harness fingerprint.

For k points spread uniformly in the unit ball of R^d, the test statistics are
the mean and the median nearest-neighbour distance. The table for level alpha
holds their lower alpha quantiles for every k (entry k-1; entry 0 is 0, as in
the authors' tables). Each Monte Carlo iteration draws one uniform sample of
n_max points and uses its first k points as the sample of size k, which leaves
every entry's distribution unchanged; this generator was checked against the
authors' own (Artemis Project 1, docs/results/unccd_repro1/null_table_validation_*.json).
Quantiles use R's default definition (type 7).
"""
from __future__ import annotations

import time

import numpy as np

# The levels stored in every null table.
ALPHAS = (0.001, 0.0015, 0.002, 0.003, 0.005, 0.0075, 0.01, 0.015, 0.02, 0.03, 0.04, 0.05,
          0.065, 0.08, 0.1, 0.125, 0.15, 0.175, 0.2, 0.25, 0.3, 0.35, 0.4)
# The alpha values a rule may choose: 15 of the stored levels, including every
# value the paper uses (0.1%, 1%, 5%, 10%, 15%) and the authors' real-data 20%.
CHOICES = (0.001, 0.002, 0.003, 0.005, 0.0075, 0.01, 0.015, 0.02, 0.03, 0.05, 0.08, 0.1, 0.15,
           0.2, 0.3)
NITER = 10000
BASE_SEED = 20261015


def uniform_ball(rng: np.random.Generator, n: int, d: int) -> np.ndarray:
    z = rng.standard_normal((n, d))
    z /= np.linalg.norm(z, axis=1, keepdims=True)
    return z * (rng.random(n) ** (1.0 / d))[:, None]


def prefix_stats(x: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    n = x.shape[0]
    sq = np.einsum("ij,ij->i", x, x)
    dist = np.sqrt(np.maximum(sq[:, None] + sq[None, :] - 2.0 * (x @ x.T), 0.0))
    np.fill_diagonal(dist, np.inf)
    cm = np.minimum.accumulate(dist, axis=1)
    upper = np.triu(np.ones((n, n), dtype=bool))
    ave = np.zeros(n)
    med = np.zeros(n)
    k = np.arange(1, n + 1)
    ave[1:] = np.where(upper, cm, 0.0).sum(axis=0)[1:] / k[1:]
    med[1:] = np.nanmedian(np.where(upper, cm, np.nan)[:, 1:], axis=0)
    return ave, med


def build(d: int, n_max: int, niter: int = NITER, seed: int | None = None, log=print) -> dict:
    seed = BASE_SEED + d if seed is None else seed
    rng = np.random.default_rng(seed)
    ave = np.empty((niter, n_max))
    med = np.empty((niter, n_max))
    t0 = time.time()
    for it in range(niter):
        ave[it], med[it] = prefix_stats(uniform_ball(rng, n_max, d))
        if log and (it + 1) % 2000 == 0:
            log(f"  nulls d={d} n_max={n_max}: {it + 1}/{niter} ({time.time() - t0:.0f}s)")
    alphas = np.asarray(ALPHAS)
    return {
        "d": d, "n_max": n_max, "niter": niter, "seed": seed, "alphas": alphas,
        "ave": np.quantile(ave, alphas, axis=0, method="linear"),   # shape (len(ALPHAS), n_max)
        "med": np.quantile(med, alphas, axis=0, method="linear"),
    }


def snap(alpha: float) -> float:
    """The choice nearest to alpha in log scale (ties to the smaller)."""
    a = float(alpha)
    if not np.isfinite(a) or a <= 0:
        raise ValueError(f"alpha must be a positive number, got {alpha!r}")
    logs = np.log(np.asarray(CHOICES))
    return float(CHOICES[int(np.argmin(np.abs(logs - np.log(a))))])


def level_index(alphas_in_table, alpha: float) -> int:
    """Row of a stored table that holds level alpha (which must be one of ALPHAS)."""
    idx = np.flatnonzero(np.isclose(np.asarray(alphas_in_table), alpha, rtol=0, atol=1e-12))
    if len(idx) != 1:
        raise ValueError(f"level {alpha} is not in the table")
    return int(idx[0])
