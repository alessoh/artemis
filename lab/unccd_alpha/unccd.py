"""UN-CCD clustering in Python: a line-by-line port of the authors' R code.

DO NOT EDIT THIS FILE. It is part of the harness fingerprint.

Source: Shi, Ceyhan and Billor, "Clustering with Uniformity- and Neighbor-Based
Random Geometric Graphs" (arXiv:2501.06268v3), code at
github.com/Rui-Shi/Cluster-Catch-Digraphs-for-Clustering-and-Outlier-Detection,
commit 9bc8032: UNCCD_clustering() in methods/clustering/UN-CCDs.R, which calls
nnccd_clustering_quantile(), nnccd.radi() with nnccd.radi.ascend.one() and
nnccd.radi.descend.one(), and nnccd.silhouette() in R/ccds/UN_CCD.R, and
dominate.mat.greedy2() and dominate.mat.ks() in R/ccds/ccdfunctions.R.

The port keeps the R code's order of operations, including its tie-breaking
(R's which.max and order() take the first of equal values; np.argmax and a
stable argsort do the same), so that it returns the same clustering. The
agreement was checked on the authors' real datasets and simulated datasets
(see validate_port.py and the validation record in the data folder).

Two speed-ups change no result. dominate.mat.greedy2() never marks a point as
covered except the one it picks, so it returns every point ordered by its
catch count (ties by index); that ordering is computed directly. The
silhouette of each candidate clustering is computed from per-cluster sums of
distances, which equals cluster::silhouette() up to floating-point rounding.
"""
from __future__ import annotations

import numpy as np

LOW_NUM = 3  # the lowest cardinality of a ball (low.num = 3 in UNCCD_clustering)


def distance_matrix(X: np.ndarray) -> np.ndarray:
    """Euclidean distances, summing squared differences column by column as R's dist() does."""
    X = np.asarray(X, dtype=np.float64)
    n, d = X.shape
    acc = np.zeros((n, n))
    for k in range(d):
        dev = X[:, k][:, None] - X[:, k][None, :]
        acc += dev * dev
    return np.sqrt(acc)


def _radius_ascend(i, ddx, o, n, env_ave, env_med):
    """nnccd.radi.ascend.one(): grow the ball around point i until the test rejects."""
    # R: m0 <- o.d[2:low.num]; members are o.d[2:j] (1-based) at step j
    m = list(o[1:LOW_NUM])
    sub = ddx[np.ix_(m, m)].copy()
    np.fill_diagonal(sub, np.inf)
    nn = sub.min(axis=1)
    for j in range(LOW_NUM, n + 1):                 # j is R's 1-based step index
        if j > LOW_NUM:
            p = o[j - 1]                            # R: o.d[j]
            prev = o[1:j - 1]                       # R: o.d[2:(j-1)]
            dp = ddx[p, prev]
            nn = np.append(np.minimum(nn, dp), dp.min())
        r = ddx[i, o[j - 1]]
        # R: env.ave[j - 1] (1-based) is the entry for j - 1 points
        if np.mean(nn) / r < env_ave[j - 2] or np.median(nn) / r < env_med[j - 2]:
            return 0.0 if j == LOW_NUM else float(ddx[i, o[j - 2]])
    return 0.0


def _radius_descend(i, ddx, o, n, env_ave_rev, env_med_rev, nn1_val, nn1_idx, nn2_val):
    """nnccd.radi.descend.one(): shrink the ball around point i until the test accepts."""
    mem = o[:n - 1]                                 # R: o.d[1:(n-1)]
    e = o[n - 1]                                    # R: o.d[n], the one point outside the ball
    nn = np.where(nn1_idx[mem] == e, nn2_val[mem], nn1_val[mem]).astype(np.float64)
    for j in range(1, n - LOW_NUM + 1):
        if j > 1:
            x = o[j - 2]                            # R: o.d[j-1] leaves the ball
            pos = np.arange(j - 1, n - 1)           # R: pos <- j:(n-1), here 0-based
            hit = pos[nn[pos] == ddx[mem[pos], x]]
            for k in hit:
                others = mem[pos[pos != k]]
                nn[k] = ddx[mem[k], others].min() if len(others) else np.inf
        r = ddx[i, o[j - 1]]
        cur = nn[j - 1:n - 1]
        # R: env.ave.rev[j + 2] (1-based)
        if np.mean(cur) / r > env_ave_rev[j + 1] and np.median(cur) / r > env_med_rev[j + 1]:
            return float(r)
    return 0.0


def _radius_descend_fast(i, ddx, o, n, env_ave_rev, env_med_rev):
    """The same search as _radius_descend(), computed for all steps at once.

    At step j (1-based) the ball holds the members at positions j-1 .. n-2 of
    o (0-based); each member's nearest-neighbour distance among them is a
    minimum over a suffix of its row, which R's loop maintains one removal at a
    time. Taking those suffix minima directly gives the same values, the means
    for every step at once, and medians only where the mean condition holds
    (the R code accepts a radius only when both conditions hold).
    """
    mem = o[:n - 1]
    Dm = ddx[np.ix_(mem, mem)].copy()
    np.fill_diagonal(Dm, np.inf)
    SM = np.minimum.accumulate(Dm[:, ::-1], axis=1)[:, ::-1]   # SM[k, q] = min over p >= q of Dm[k, p]
    m = n - 1
    lower = np.tril(np.ones((m, m), dtype=bool))               # rows k >= column q
    counts = np.arange(m, 0, -1)                               # members at step j = q + 1: m - q
    sums = np.where(lower, SM, 0.0).sum(axis=0)
    steps = np.arange(1, n - LOW_NUM + 1)                      # R's j
    q = steps - 1
    r = ddx[i, o[q]]
    with np.errstate(divide="ignore", invalid="ignore"):
        # a pre-filter with a little slack; the exact test below decides
        mean_ok = (sums[q] / counts[q]) / r > env_ave_rev[steps + 1] * (1.0 - 1e-9)
    for j in steps[mean_ok]:
        cur = SM[j - 1:, j - 1]
        # the same values R averages, in R's member order, so np.mean matches the loop version
        if np.mean(cur) / r[j - 1] > env_ave_rev[j + 1] and np.median(cur) / r[j - 1] > env_med_rev[j + 1]:
            return float(r[j - 1])
    return 0.0


def radii(X: np.ndarray, env_ave: np.ndarray, env_med: np.ndarray, method: str = "ascend",
          ddx: np.ndarray | None = None, exact_loop: bool = False) -> np.ndarray:
    """nnccd.radi(): the covering-ball radius of every point.

    env_ave[k-1] and env_med[k-1] are the lower-tail null quantiles of the mean
    and median nearest-neighbour distance for k points (entry 0 is 0).
    """
    if ddx is None:
        ddx = distance_matrix(X)
    n = ddx.shape[0]
    env_ave = np.asarray(env_ave, dtype=np.float64)[:n]
    env_med = np.asarray(env_med, dtype=np.float64)[:n]
    if len(env_ave) < n or len(env_med) < n:
        raise ValueError("the null table is shorter than the data")
    R = np.zeros(n)
    if method == "ascend":
        for i in range(n):
            o = np.argsort(ddx[i], kind="stable")
            R[i] = _radius_ascend(i, ddx, o, n, env_ave, env_med)
    elif method == "descend":
        env_ave_rev = env_ave[::-1]
        env_med_rev = env_med[::-1]
        dd0 = ddx.copy()
        np.fill_diagonal(dd0, np.inf)
        nn1_idx = np.argmin(dd0, axis=1)
        nn1_val = dd0[np.arange(n), nn1_idx]
        dd0[np.arange(n), nn1_idx] = np.inf
        nn2_val = dd0.min(axis=1)
        del dd0
        for i in range(n):
            o = np.argsort(-ddx[i], kind="stable")  # R: order(decreasing = TRUE), ties in index order
            if exact_loop:
                R[i] = _radius_descend(i, ddx, o, n, env_ave_rev, env_med_rev, nn1_val, nn1_idx, nn2_val)
            else:
                R[i] = _radius_descend_fast(i, ddx, o, n, env_ave_rev, env_med_rev)
    else:
        raise ValueError("method must be 'ascend' or 'descend'")
    return R


def _dominate_ks(A: np.ndarray, ks: np.ndarray) -> list[int]:
    """dominate.mat.ks(): repeatedly take the uncovered point with the largest ks."""
    ks = ks.astype(np.float64).copy()
    n = A.shape[0]
    covered = np.zeros(n, dtype=bool)
    S = []
    while not covered.all():
        i = int(np.argmax(ks))
        row = A[i] & ~covered                      # R zeroes covered columns before reading the row
        covered |= row
        S.append(i)
        ks[covered] = -np.inf
    return S


def graph(X: np.ndarray, env_ave, env_med, method: str = "ascend", ddx: np.ndarray | None = None) -> dict:
    """nnccd_clustering_quantile() with dom.method = "greedy2"."""
    if ddx is None:
        ddx = distance_matrix(X)
    n = ddx.shape[0]
    r = radii(X, env_ave, env_med, method, ddx)
    M = ddx <= r[:, None]                           # R: matrix(as.integer(ddatax <= r), length(r))
    score = M.sum(axis=1)
    D = np.argsort(-score, kind="stable")          # dominate.mat.greedy2(): all points, by score, ties by index
    R = r[D]
    MD = M[D].astype(np.float32)
    inter = (MD @ MD.T) > 0                         # two balls catch a common point
    np.fill_diagonal(inter, True)
    d_ind = _dominate_ks(inter, score[D])
    int_d = D[d_ind]
    int_r = R[d_ind]
    catch = M[int_d].sum(axis=1)
    return {"Int.D": int_d, "Int.R": int_r, "D": D, "R": R, "catch": catch, "radii": r}


def _silhouette_mean(labels: np.ndarray, ddx: np.ndarray) -> float:
    """Mean of cluster::silhouette() widths for a labelling (2 <= clusters < n)."""
    uniq, lab = np.unique(labels, return_inverse=True)
    k = len(uniq)
    n = len(lab)
    onehot = np.zeros((n, k))
    onehot[np.arange(n), lab] = 1.0
    sums = ddx @ onehot                             # sum of distances from each point to each cluster
    counts = onehot.sum(axis=0)
    own = sums[np.arange(n), lab]
    own_count = counts[lab]
    with np.errstate(divide="ignore", invalid="ignore"):
        a = own / (own_count - 1)
        avg = sums / counts[None, :]
    avg[np.arange(n), lab] = np.inf
    b = avg.min(axis=1)
    s = np.where(b != a, (b - a) / np.maximum(a, b), 0.0)
    s = np.where(own_count == 1, 0.0, s)
    return float(np.mean(s))


def _assign(int_d, int_r, ddx, i):
    """nnccd.clustering.nonvalid() with the first i dominators: labels 1..i."""
    ddx_d = ddx[:, int_d[:i]] + np.finfo(float).eps
    with np.errstate(divide="ignore", invalid="ignore"):
        ratio = ddx_d / int_r[:i][None, :]
    return np.argmin(ratio, axis=1) + 1             # which.min: the first of equal values


def cluster(X: np.ndarray, env_ave, env_med, method: str = "ascend", ddx: np.ndarray | None = None) -> dict:
    """UNCCD_clustering(): the labelling with the largest mean silhouette.

    Returns labels (1-based, as in R), si (that silhouette), si_ind (the number
    of dominating balls used) and the radii.
    """
    if ddx is None:
        ddx = distance_matrix(X)
    g = graph(X, env_ave, env_med, method, ddx)
    n = ddx.shape[0]
    len_d = len(g["Int.D"])                         # min.cls = 0: every dominator qualifies
    maxsi = 0.0
    si_ind = 1
    result = np.ones(n, dtype=int)
    if len_d >= 2:
        for i in range(2, len_d + 1):
            temp = _assign(g["Int.D"], g["Int.R"], ddx, i)
            k = len(np.unique(temp))
            if k < 2:
                datasi = 0.0
            elif k >= n:
                raise RuntimeError("cluster::silhouette() returns NA when every point is its own cluster")
            else:
                datasi = _silhouette_mean(temp, ddx)
            if datasi > maxsi and int(np.sum(temp == i)) > 1:
                result = temp
                maxsi = datasi
                si_ind = i
    return {"labels": result, "si": maxsi, "si_ind": si_ind, "radii": g["radii"],
            "n_dominators": len_d}
