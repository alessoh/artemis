"""The label-free toolkit an experiment receives for each dataset.

DO NOT EDIT THIS FILE. It is part of the harness fingerprint.

An experiment's choose(X, kit, seed) sees one unlabelled dataset X and this
kit. Everything here is computed from X and from the null tables alone; no
method can reach a label. The kit offers:

  kit.n, kit.d          the number of points and the dimension
  kit.alphas            the alpha values that may be chosen (others are snapped
                        to the nearest in log scale)
  kit.directions        ("ascend", "descend"), the two radius searches of the code
  kit.data()            a copy of X
  kit.distances()       a copy of the Euclidean distance matrix
  kit.cluster(alpha, direction="ascend")
                        UN-CCD on X: a dict with "labels" (1-based integers),
                        "silhouette" (the mean silhouette the method maximised),
                        "balls" (the number of dominating balls it used),
                        "clusters" (distinct labels) and "radii"
  kit.cluster_points(points, alpha, direction="ascend")
                        UN-CCD on any other point set of the same dimension
                        (a subsample, a perturbed copy), at most kit.max_points rows
  kit.null_quantiles(alpha)
                        the null table for this dimension: two arrays whose
                        entry k-1 is the lower alpha quantile of the mean and of
                        the median nearest-neighbour distance of k points
                        uniform in the unit ball
  kit.silhouette(labels)
                        the mean silhouette of any labelling of X

kit.cluster() reads results computed in advance by the same code (the cache in
data/ for dev and val; the humans build the same cache for test), so it is
instant; without a cache it computes them. kit.cluster_points() always computes.
"""
from __future__ import annotations

import numpy as np

import nulls
import unccd

DIRECTIONS = ("ascend", "descend")


class Kit:
    def __init__(self, X: np.ndarray, table: dict, cached: dict | None = None):
        self._X = np.asarray(X, dtype=np.float64)
        self.n, self.d = self._X.shape
        self.alphas = tuple(nulls.CHOICES)
        self.directions = DIRECTIONS
        self._table = table                      # {"alphas", "ave", "med"} for this dimension
        self.max_points = int(table["ave"].shape[1])
        self._ddx = None
        self._cached = cached or {}               # {(alpha, direction): result}
        self._memo: dict = {}

    # ------------------------------------------------------------ helpers
    def _env(self, alpha: float):
        a = nulls.snap(alpha)
        row = nulls.level_index(self._table["alphas"], a)
        return a, self._table["ave"][row], self._table["med"][row]

    def _dist(self) -> np.ndarray:
        if self._ddx is None:
            self._ddx = unccd.distance_matrix(self._X)
        return self._ddx

    @staticmethod
    def _direction(direction: str) -> str:
        if direction not in DIRECTIONS:
            raise ValueError(f"direction must be one of {DIRECTIONS}")
        return direction

    @staticmethod
    def _pack(out: dict) -> dict:
        labels = np.asarray(out["labels"], dtype=int)
        return {"labels": labels.copy(), "silhouette": float(out["si"]), "balls": int(out["si_ind"]),
                "clusters": int(len(np.unique(labels))), "radii": np.asarray(out["radii"], dtype=float).copy()}

    # ------------------------------------------------------------ the toolkit
    def data(self) -> np.ndarray:
        return self._X.copy()

    def distances(self) -> np.ndarray:
        return self._dist().copy()

    def null_quantiles(self, alpha: float):
        _, ave, med = self._env(alpha)
        return ave.copy(), med.copy()

    def cluster(self, alpha: float, direction: str = "ascend") -> dict:
        direction = self._direction(direction)
        a, ave, med = self._env(alpha)
        key = (a, direction)
        if key in self._cached:
            hit = self._cached[key]
            return {k: (v.copy() if isinstance(v, np.ndarray) else v) for k, v in hit.items()}
        if key not in self._memo:
            self._memo[key] = self._pack(unccd.cluster(self._X, ave, med, direction, self._dist()))
        hit = self._memo[key]
        return {k: (v.copy() if isinstance(v, np.ndarray) else v) for k, v in hit.items()}

    def cluster_points(self, points, alpha: float, direction: str = "ascend") -> dict:
        direction = self._direction(direction)
        P = np.asarray(points, dtype=np.float64)
        if P.ndim != 2 or P.shape[1] != self.d:
            raise ValueError(f"points must be an array with {self.d} columns")
        if P.shape[0] > self.max_points or P.shape[0] < 4:
            raise ValueError(f"points must have between 4 and {self.max_points} rows")
        _, ave, med = self._env(alpha)
        return self._pack(unccd.cluster(P, ave, med, direction))

    def silhouette(self, labels) -> float:
        lab = np.asarray(labels)
        if lab.shape != (self.n,):
            raise ValueError("labels must have one entry per point")
        k = len(np.unique(lab))
        if k < 2 or k >= self.n:
            return 0.0
        return unccd._silhouette_mean(lab, self._dist())
