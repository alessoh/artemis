"""Frozen: read Lanyon AI's Racket specifications into exact SymPy models.

DO NOT EDIT THIS FILE. It is part of the harness fingerprint.

Lanyon's specifications (github.com/lanyonai, `specifications/*.rkt`) use a
small subset of Racket: `define`, `hash`, `list`, `let`, quote ('), quasiquote
(`) and unquote (,), numbers, strings and symbols. Inside quasiquoted
expressions the operators are + - * / sqrt abs max min and, in assumptions,
> >= < <=. This module reads that subset exactly (no Racket installation is
needed), evaluates the structure, and turns every formula into a SymPy
expression with exact rational constants (0.5 becomes 1/2).

A file defines a physics table (it has 'fluxes) and a solver table (it has
'speeds). From them a SpecModel holds, for each coordinate direction:
  flux[d]        the flux of every state variable (SymPy expressions)
  listed[d]      the wave speeds the specification lists
  speeds[d]      the solver's two speeds, in variables with _L and _R suffixes
and the state, parameter and coordinate names and the declared assumptions.

Anything outside the supported subset raises SpecError, so a specification is
never read silently in a different way from what it says.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from fractions import Fraction
from pathlib import Path

import sympy as sp


class SpecError(ValueError):
    """The file uses something this reader does not support."""


class Sym(str):
    """A Racket symbol."""


# ------------------------------------------------------------------ reader
_TOKEN = re.compile(r"""\s*(?:(;[^\n]*)|([()\[\]])|([`',])|("(?:[^"\\]|\\.)*")|([^\s()\[\]`',";]+))""")
_NUMBER = re.compile(r"^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$")


def tokenize(text: str) -> list[str]:
    text = re.sub(r"(?m)^[ \t]*#lang[^\n]*$", "", text)
    out, pos = [], 0
    while pos < len(text):
        m = _TOKEN.match(text, pos)
        if not m or m.end() == pos:
            if text[pos:].strip() == "":
                break
            raise SpecError(f"cannot read text at character {pos}: {text[pos:pos + 30]!r}")
        pos = m.end()
        comment, paren, quote, string, atom = m.groups()
        if comment:
            continue
        tok = paren or quote or string or atom
        if tok:
            out.append(tok)
    return out


def read_all(text: str) -> list:
    tokens = tokenize(text)
    pos = 0

    def read():
        nonlocal pos
        if pos >= len(tokens):
            raise SpecError("unexpected end of file")
        tok = tokens[pos]
        pos += 1
        if tok in ("(", "["):
            close = ")" if tok == "(" else "]"
            items = []
            while True:
                if pos >= len(tokens):
                    raise SpecError("unclosed parenthesis")
                if tokens[pos] == close:
                    pos += 1
                    return items
                if tokens[pos] in (")", "]"):
                    raise SpecError("mismatched parenthesis")
                items.append(read())
        if tok in (")", "]"):
            raise SpecError("unexpected closing parenthesis")
        if tok == "`":
            return [Sym("quasiquote"), read()]
        if tok == "'":
            return [Sym("quote"), read()]
        if tok == ",":
            return [Sym("unquote"), read()]
        if tok.startswith('"'):
            return tok[1:-1]
        if _NUMBER.match(tok):
            return Fraction(tok) if "e" not in tok.lower() else Fraction(float(tok))
        return Sym(tok)

    forms = []
    while pos < len(tokens):
        forms.append(read())
    return forms


# ------------------------------------------------------------------ evaluator
def _quasi(x, env):
    if isinstance(x, list):
        if len(x) == 2 and x[0] == "unquote":
            return evaluate(x[1], env)
        if len(x) == 2 and x[0] == "quasiquote":
            raise SpecError("nested quasiquote is not supported")
        return [_quasi(item, env) for item in x]
    return x


def evaluate(x, env: dict):
    if isinstance(x, Fraction) or isinstance(x, str) and not isinstance(x, Sym):
        return x
    if isinstance(x, Sym):
        if x in env:
            return env[x]
        raise SpecError(f"unbound name {x}")
    if not isinstance(x, list) or not x:
        raise SpecError(f"cannot evaluate {x!r}")
    head = x[0]
    if head == "quote":
        return Sym(x[1]) if isinstance(x[1], Sym) else x[1]
    if head == "quasiquote":
        return _quasi(x[1], env)
    if head == "list":
        return [evaluate(a, env) for a in x[1:]]
    if head == "hash":
        args = [evaluate(a, env) for a in x[1:]]
        if len(args) % 2:
            raise SpecError("hash with an odd number of arguments")
        return {str(args[i]): args[i + 1] for i in range(0, len(args), 2)}
    if head == "let":
        bindings, body = x[1], x[2:]
        inner = dict(env)
        for b in bindings:
            if not (isinstance(b, list) and len(b) == 2 and isinstance(b[0], Sym)):
                raise SpecError(f"bad let binding {b!r}")
            inner[b[0]] = evaluate(b[1], env)          # let, not let*
        result = None
        for form in body:
            result = evaluate(form, inner)
        return result
    raise SpecError(f"unsupported form ({head} ...)")


def evaluate_file(text: str) -> dict:
    env: dict = {}
    order = []
    for form in read_all(text):
        if isinstance(form, list) and form and form[0] == "define":
            if len(form) != 3 or not isinstance(form[1], Sym):
                raise SpecError("unsupported define")
            env[form[1]] = evaluate(form[2], env)
            order.append(form[1])
        else:
            raise SpecError(f"unsupported top-level form {form!r:.60}")
    return {name: env[name] for name in order}


# ------------------------------------------------------------------ to SymPy
_SYMBOLS: dict[str, sp.Symbol] = {}


def symbol(name: str) -> sp.Symbol:
    if name not in _SYMBOLS:
        _SYMBOLS[name] = sp.Symbol(name, real=True)
    return _SYMBOLS[name]


def to_sympy(x):
    if isinstance(x, Fraction):
        return sp.Rational(x.numerator, x.denominator)
    if isinstance(x, Sym):
        return symbol(str(x))
    if isinstance(x, list) and x and isinstance(x[0], Sym):
        op, args = str(x[0]), [to_sympy(a) for a in x[1:]]
        if op == "+":
            return sp.Add(*args) if args else sp.Integer(0)
        if op == "-":
            if len(args) == 1:
                return -args[0]
            return args[0] - sp.Add(*args[1:])
        if op == "*":
            return sp.Mul(*args) if args else sp.Integer(1)
        if op == "/":
            if len(args) == 1:
                return 1 / args[0]
            out = args[0]
            for a in args[1:]:
                out = out / a
            return out
        if op == "sqrt" and len(args) == 1:
            return sp.sqrt(args[0])
        if op == "abs" and len(args) == 1:
            return sp.Abs(args[0])
        if op == "max":
            return sp.Max(*args)
        if op == "min":
            return sp.Min(*args)
        if op in (">", ">=", "<", "<=") and len(args) == 2:
            return {">": sp.StrictGreaterThan, ">=": sp.GreaterThan,
                    "<": sp.StrictLessThan, "<=": sp.LessThan}[op](args[0], args[1], evaluate=False)
        raise SpecError(f"unsupported operator {op} with {len(args)} arguments")
    raise SpecError(f"cannot convert {x!r:.80} to SymPy")


# ------------------------------------------------------------------ model
@dataclass
class SpecModel:
    name: str                      # file stem, e.g. ideal_mhd_1d
    family: str                    # repository name
    state: list[str]
    parameters: list[str]
    coordinates: list[str]
    state_assumptions: list        # SymPy relationals in state variables
    parameter_assumptions: list    # SymPy relationals in parameters
    flux: list[list]               # [direction][variable]
    listed: list[list]             # [direction][wave]
    speeds: list[list]             # [direction][2] in _L/_R variables
    solver: str
    positive: set = field(default_factory=set)   # variables declared > 0 or >= 0
    cname: str = ""                # the physics table's 'name with - replaced by _ (Lanyon's C prefix)

    @property
    def directions(self) -> int:
        return len(self.flux)

    def task_names(self) -> list[str]:
        return [f"{self.family}/{self.name}/{self.coordinates[d]}" for d in range(self.directions)]


def _sided(name: str, side: str) -> str:
    return f"{name}_{side}"


def load_spec(path: Path, family: str) -> SpecModel:
    tables = evaluate_file(Path(path).read_text(encoding="utf-8"))
    physics = [t for t in tables.values() if isinstance(t, dict) and "fluxes" in t]
    solvers = [t for t in tables.values() if isinstance(t, dict) and "speeds" in t]
    if len(physics) != 1 or len(solvers) != 1:
        raise SpecError(f"{path.name}: expected one physics table and one solver table, "
                        f"found {len(physics)} and {len(solvers)}")
    ph, so = physics[0], solvers[0]
    state = [str(s) for s in ph["state"]]
    params = [str(s) for s in ph["parameters"]]
    coords = [str(s) for s in ph["coordinates"]]
    flux = [[to_sympy(e) for e in row] for row in ph["fluxes"]]
    listed = [[to_sympy(e) for e in row] for row in ph["wavespeeds"]]
    speeds = [[to_sympy(e) for e in row] for row in so["speeds"]]
    s_assume = [to_sympy(e) for e in ph.get("state-assumptions", [])]
    p_assume = [to_sympy(e) for e in ph.get("parameters-assumptions", [])]
    if not (len(flux) == len(listed) == len(speeds)):
        raise SpecError(f"{path.name}: fluxes, wavespeeds and speeds have different numbers of directions")
    for d in range(len(flux)):
        if len(flux[d]) != len(state):
            raise SpecError(f"{path.name}: direction {d} has {len(flux[d])} fluxes for {len(state)} variables")
        if len(listed[d]) != len(state):
            raise SpecError(f"{path.name}: direction {d} lists {len(listed[d])} speeds for {len(state)} variables")
        if len(speeds[d]) != 2:
            raise SpecError(f"{path.name}: direction {d} solver speeds are not a pair")
    allowed = {symbol(n) for n in state + params + coords}
    sided = {symbol(_sided(n, s)) for n in state + coords for s in ("L", "R")} | {symbol(n) for n in params}
    for d in range(len(flux)):
        for e in flux[d] + listed[d]:
            extra = e.free_symbols - allowed
            if extra:
                raise SpecError(f"{path.name}: unknown names {sorted(map(str, extra))} in a flux or listed speed")
        for e in speeds[d]:
            extra = e.free_symbols - sided
            if extra:
                raise SpecError(f"{path.name}: unknown names {sorted(map(str, extra))} in the solver speeds")
    positive = set()
    for rel in s_assume + p_assume:
        if (isinstance(rel, (sp.StrictGreaterThan, sp.GreaterThan)) and rel.rhs == 0
                and isinstance(rel.lhs, sp.Symbol)):
            positive.add(str(rel.lhs))
    return SpecModel(name=Path(path).stem, family=family, state=state, parameters=params, coordinates=coords,
                     state_assumptions=s_assume, parameter_assumptions=p_assume, flux=flux, listed=listed,
                     speeds=speeds, solver=str(so.get("name", "")), positive=positive,
                     cname=str(ph.get("name", Path(path).stem)).replace("-", "_"))
