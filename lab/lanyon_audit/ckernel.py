"""Frozen: evaluate Lanyon's own generated C kernels at given points (hypothesis H3).

DO NOT EDIT THIS FILE. It is part of the harness fingerprint.

For a task, the specification's C file (implementations/<spec>.c in the same
repository) is compiled together with a small driver. The C file is included
unchanged, with its empty main() renamed. The driver reads records from stdin:

  S  coords_L coords_R state_L state_R params   -> prints the two solver speeds
  F  coords state params                        -> prints the flux in the task's direction

Function and type names follow Lanyon's generator:
  <spec>_<solver>_<dir>_speed_family(C_L, C_R, U_L, U_R, P, out)
  <spec>_<dir>_flux(C, P, U, out)
with <solver> the specification's solver name with '-' replaced by '_'
(lax_friedrichs, wave_propagation, p1_dg, p2_dg).

check_violation() evaluates the C speeds at a point and a central
finite-difference Jacobian of the C flux (relative step 1e-6) at both states,
and reports whether the C dissipation speed equals the specification's
(relative difference at most 1e-9) and whether the finite-difference spectral
radius exceeds it by more than 1e-6 relative (preregistration.md, H3).
"""
from __future__ import annotations

import shutil
import subprocess
import tempfile
from pathlib import Path

import numpy as np

import judge

FD_STEP = 1e-6          # relative to |u_j| (to 1e-3 max|u| when u_j = 0)
SPEED_REL_TOL = 1e-9
EXCESS_REL_TOL = 1e-6


def c_names(task: judge.Task) -> dict:
    s = task.spec
    solver = s.solver.replace("-", "_")
    d = s.coordinates[task.d]
    c = s.cname        # Lanyon's C prefix: the physics table's 'name, with - replaced by _
    return {"speed_fn": f"{c}_{solver}_{d}_speed_family", "speed_t": f"{c}_{solver}_speed_family",
            "flux_fn": f"{c}_{d}_flux", "flux_t": f"{c}_flux", "state_t": f"{c}_state",
            "param_t": f"{c}_parameters", "coord_t": f"{c}_coordinates"}


def driver_source(task: judge.Task, c_file: Path) -> str:
    s, n = task.spec, c_names(task)

    def reads(var, fields):
        return "".join(f'  if (scanf("%lf", &{var}.{f}) != 1) return 1;\n' for f in fields)

    coords = list(s.coordinates)
    return f"""#include <stdio.h>
#define main lanyon_generated_main
#include "{c_file.name}"
#undef main
int main(void) {{
  char kind[4];
  while (scanf("%3s", kind) == 1) {{
    {n['coord_t']} CL, CR; {n['state_t']} UL, UR; {n['param_t']} P;
    if (kind[0] == 'S') {{
{reads('CL', coords)}{reads('CR', coords)}{reads('UL', s.state)}{reads('UR', s.state)}{reads('P', s.parameters)}
      {n['speed_t']} out;
      {n['speed_fn']}(&CL, &CR, &UL, &UR, &P, &out);
      printf("%.17g %.17g\\n", out.speed1, out.speed2);
    }} else {{
{reads('CL', coords)}{reads('UL', s.state)}{reads('P', s.parameters)}
      {n['flux_t']} F;
      {n['flux_fn']}(&CL, &P, &UL, &F);
      printf("{' '.join(['%.17g'] * len(s.state))}\\n", {', '.join(f'F.flux_{v}' for v in s.state)});
    }}
  }}
  return 0;
}}
"""


class CKernel:
    """A compiled driver for one task; call speeds() and flux() on many inputs."""

    def __init__(self, task: judge.Task, c_file: Path, workdir: Path):
        self.task = task
        self.dir = Path(workdir)
        shutil.copy(c_file, self.dir / c_file.name)
        (self.dir / "driver.c").write_text(driver_source(task, c_file))
        self.exe = self.dir / "driver"
        cc = shutil.which("gcc") or shutil.which("cc")
        if cc is None:
            raise RuntimeError("no C compiler (gcc) found")
        res = subprocess.run([cc, "-O0", "-ffp-contract=off", "-std=c99", "-w", "-o", str(self.exe),
                              str(self.dir / "driver.c"), "-lm"], capture_output=True, text=True)
        if res.returncode != 0:
            raise RuntimeError(f"compiling {c_file.name} failed:\n{res.stderr[-2000:]}")

    def _run(self, lines: list[str]) -> list[list[float]]:
        res = subprocess.run([str(self.exe)], input="\n".join(lines) + "\n", capture_output=True, text=True,
                             timeout=600)
        if res.returncode != 0:
            raise RuntimeError(f"driver failed: {res.stderr[-500:]}")
        return [[float(v) for v in row.split()] for row in res.stdout.strip().splitlines()]

    @staticmethod
    def _fmt(values) -> str:
        return " ".join(repr(float(v)) for v in values)

    def speeds(self, point: dict) -> list[float]:
        X = point["X"]
        return self._run([f"S {self._fmt(X)} {self._fmt(X)} {self._fmt(point['L'])} {self._fmt(point['R'])} "
                          f"{self._fmt(point['P'])}"])[0]

    def fd_jacobian(self, state, P, X) -> np.ndarray:
        n = len(state)
        lines, steps = [], []
        for j in range(n):
            scale = abs(state[j]) if state[j] != 0 else max(1e-3 * max(abs(v) for v in state), 1e-8)
            h = FD_STEP * scale
            steps.append(h)
            for sign in (1, -1):
                u = list(state)
                u[j] += sign * h
                lines.append(f"F {self._fmt(X)} {self._fmt(u)} {self._fmt(P)}")
        out = self._run(lines)
        J = np.zeros((n, n))
        for j in range(n):
            J[:, j] = (np.array(out[2 * j]) - np.array(out[2 * j + 1])) / (2 * steps[j])
        return J


def preflight(tasks, root: Path) -> list[str]:
    """Compile a driver for every task and evaluate it once at a baseline point; return problems."""
    import numpy as _np
    problems = []
    for task in tasks:
        try:
            with tempfile.TemporaryDirectory() as tmp:
                k = CKernel(task, c_file_for(task, root), Path(tmp))
                rng = _np.random.default_rng(0)
                for _ in range(20000):
                    p = judge.sample_point(task, rng)
                    try:
                        e = judge.evaluate_point(task, p)
                    except judge.Inadmissible:
                        continue
                    s = k.speeds(e["point"])
                    a = max(abs(s[0]), abs(s[1]))
                    if abs(a - e["amax"]) > SPEED_REL_TOL * abs(e["amax"]):
                        problems.append(f"{task.name}: C speed {a!r} differs from the specification's {e['amax']!r}")
                    break
        except Exception as exc:  # noqa: BLE001
            problems.append(f"{task.name}: {type(exc).__name__}: {str(exc)[:200]}")
    return problems


def c_file_for(task: judge.Task, root: Path) -> Path:
    return Path(root) / task.spec.family / "implementations" / f"{task.spec.name}.c"


def check_violation(task: judge.Task, point: dict, root: Path) -> dict:
    point = judge.validate_point(task, point)
    with tempfile.TemporaryDirectory() as tmp:
        k = CKernel(task, c_file_for(task, root), Path(tmp))
        s = k.speeds(point)
        amax_c = max(abs(s[0]), abs(s[1]))
        rho_fd = 0.0
        for side in ("L", "R"):
            J = k.fd_jacobian(point[side], point["P"], point["X"])
            rho_fd = max(rho_fd, float(np.max(np.abs(np.linalg.eigvals(J)))))
    spec_eval = judge.evaluate_point(task, point)
    same_speed = abs(amax_c - spec_eval["amax"]) <= SPEED_REL_TOL * abs(spec_eval["amax"])
    excess = rho_fd > amax_c * (1 + EXCESS_REL_TOL)
    return {"task": task.name, "c_amax": amax_c, "spec_amax": spec_eval["amax"], "fd_spectral_radius": rho_fd,
            "spec_spectral_radius": spec_eval["rho"], "c_speed_equals_spec": bool(same_speed),
            "c_violation": bool(excess), "holds": bool(same_speed and excess)}
