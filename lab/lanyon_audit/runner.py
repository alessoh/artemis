"""Frozen runner: executes one experiment's search() on a list of tasks.

DO NOT EDIT THIS FILE. It is part of the harness fingerprint.

The harness starts this script with `python -E`, in a new process group, from
an empty temporary folder, with a minimal environment. It reads one JSON
message on stdin: a one-time token, the folder holding Lanyon's
repositories, the task names and one integer seed per task (computed by the
harness; the seed string itself never reaches this process). It compiles those tasks with the
frozen judge (reading the specification files before any guard exists),
installs an audit hook, imports the experiment from the copy the harness
checked, and prints "<token> READY". For each task it calls
search(info, kit, seed) and prints "<token> POINTS <json>"; at the end
"<token> DONE".

After the hook is installed the process may open files only for reading and
only inside the Python installation, the lab's own code files or the
experiment's copy; it may not start processes, open network connections or
change the hook.
"""

import importlib.util
import json
import math
import os
import random
import sys
import time
import traceback
from pathlib import Path

import numpy as np

PREIMPORT = ("scipy", "scipy.optimize", "scipy.stats", "scipy.special", "scipy.linalg")
DENIED_EVENTS = ("subprocess.Popen", "os.system", "os.exec", "os.posix_spawn", "os.spawn",
                 "os.fork", "os.forkpty", "pty.spawn", "socket.", "urllib.", "http.",
                 "ftplib.", "smtplib.", "webbrowser.", "sys.addaudithook", "os.remove",
                 "os.unlink", "os.rename", "os.rmdir", "os.mkdir", "os.chmod", "os.putenv",
                 "os.unsetenv", "shutil.")
CODE_FILES = ("kit.py", "judge.py", "specs.py")


def install_guard(experiment_path, lab_dir):
    roots = {os.path.normcase(os.path.realpath(p)) for p in
             (sys.prefix, sys.base_prefix, sys.exec_prefix, sys.base_exec_prefix,
              os.path.dirname(np.__file__), os.path.dirname(os.path.dirname(np.__file__)))}
    code_files = {os.path.normcase(os.path.realpath(os.path.join(lab_dir, f))) for f in CODE_FILES}
    allowed_file = os.path.normcase(os.path.realpath(experiment_path))

    def inside(path):
        real = os.path.normcase(os.path.realpath(path))
        if real == allowed_file or real in code_files:
            return True
        for root in roots:
            try:
                if os.path.commonpath([real, root]) == root:
                    return True
            except ValueError:
                continue
        return False

    def hook(event, args):
        if event == "open":
            path, mode, flags = (list(args) + [None, None, None])[:3]
            if isinstance(path, int):
                return
            if isinstance(path, bytes):
                path = os.fsdecode(path)
            writing = (isinstance(mode, str) and any(c in mode for c in "wax+")) or (
                isinstance(flags, int) and flags & (os.O_WRONLY | os.O_RDWR | os.O_CREAT))
            if writing or not inside(str(path)):
                raise PermissionError(f"the experiment may not open {path!r}")
        elif event.startswith(DENIED_EVENTS):
            raise PermissionError(f"the experiment may not use {event}")

    sys.addaudithook(hook)


def clean_points(points, max_points):
    """JSON-safe copy of the experiment's answer (lists of finite floats)."""
    if not isinstance(points, (list, tuple)):
        raise ValueError("search() must return a list of points")
    out = []
    for p in list(points)[:max_points]:
        if not isinstance(p, dict):
            raise ValueError("each point must be a dict with keys L, R, P, X")
        q = {}
        for key in ("L", "R", "P", "X"):
            v = p.get(key, [])
            v = [float(x) for x in v]
            if not all(math.isfinite(x) for x in v):
                raise ValueError("a point has a non-finite value")
            q[key] = v
        out.append(q)
    return out


def main():
    here = str(Path(__file__).resolve().parent)
    sys.path[:] = [p for p in sys.path if p not in ("", ".", here)]
    sys.dont_write_bytecode = True
    message = json.loads(sys.stdin.read())
    token = message["token"]
    out = os.fdopen(os.dup(1), "w")
    os.dup2(2, 1)
    sys.stdout = sys.stderr

    def emit(kind, payload=""):
        out.write(f"{token} {kind} {payload}\n")
        out.flush()

    try:
        names = list(message["tasks"])
        task_seeds = [int(x) for x in message["task_seeds"]]
        if len(task_seeds) != len(names):
            raise RuntimeError("one seed per task is required")
        root = message["root"]
        for name in PREIMPORT:
            importlib.import_module(name)
        for name in ("specs", "judge", "kit"):
            spec = importlib.util.spec_from_file_location(name, os.path.join(here, f"{name}.py"))
            module = importlib.util.module_from_spec(spec)
            sys.modules[name] = module
            spec.loader.exec_module(module)
        judge, kitmod = sys.modules["judge"], sys.modules["kit"]
        wanted = set(names)
        tasks = {}
        for family, path in judge.spec_files(Path(root)):
            prefix = f"{family}/{path.stem}/"
            if not any(n.startswith(prefix) for n in wanted):
                continue
            for t in judge.compile_spec(sys.modules["specs"].load_spec(path, family)):
                if t.name in wanted:
                    tasks[t.name] = t
        missing = wanted - set(tasks)
        if missing:
            raise RuntimeError(f"unknown tasks: {sorted(missing)[:5]}")
        del message
        random.seed(0)
        np.random.seed(0)
        spec = importlib.util.spec_from_file_location("artemis_experiment", sys.argv[1])
        module = importlib.util.module_from_spec(spec)
        install_guard(sys.argv[1], here)
        spec.loader.exec_module(module)
        if not hasattr(module, "search"):
            raise RuntimeError("the experiment must define search(info, kit, seed)")
        emit("READY")
        for i, name in enumerate(names):
            task = tasks[name]
            kit = kitmod.Kit(task)
            task_seed = task_seeds[i]
            t0 = time.process_time()
            points = module.search(dict(kit.info), kit, task_seed)
            cpu = time.process_time() - t0
            emit("POINTS", json.dumps({"i": i, "task": name, "points": clean_points(points, kitmod.MAX_POINTS),
                                       "calls": kit.calls, "cpu": round(cpu, 3)}))
        emit("DONE")
    except BaseException:  # noqa: BLE001
        emit("ERROR", json.dumps(traceback.format_exc(limit=6)))


if __name__ == "__main__":
    main()
