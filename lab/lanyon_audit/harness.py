# ---------------------------------------------------------------- integrity
def sha256_file(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def fingerprint() -> dict[str, str]:
    names = ("harness", "runner", "kit", "judge", "specs", "ckernel")
    out = {n: sha256_file(HERE / f"{n}.py") for n in names}
    out["data"] = sha256_file(MANIFEST) if MANIFEST.exists() else "missing"
    return out


def check_data() -> None:
    if not MANIFEST.exists():
        raise HarnessError("data/manifest.json is missing; restore it from git.")
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    for rel, expected in manifest["sha256"].items():
        path = LANYON_ROOT / rel
        if not path.exists():
            raise HarnessError(f"{rel} is missing. Run: python lab/lanyon_audit/prepare_data.py")
        if sha256_file(path) != expected:
            raise HarnessError(f"{rel} does not match the manifest; the Lanyon snapshot is altered. "
                               "Delete lab/lanyon_audit/work/lanyon and run prepare_data.py again.")
    found = {f"{fam}/specifications/{p.name}" for fam, p in judge.spec_files(LANYON_ROOT)}
    listed = {rel for rel in manifest["sha256"] if rel.endswith(".rkt")}
    if found != listed:
        raise HarnessError(f"the specification files differ from the manifest ({len(found ^ listed)} files); "
                           "delete lab/lanyon_audit/work/lanyon and run prepare_data.py again.")


