"""Artemis harness: the wave-speed audit of Lanyon AI's verified-solver specifications.

DO NOT EDIT THIS FILE. Agents edit copies of experiment.py in trials/; humans
change this file, and every change shows up in its fingerprint.

The question (preregistration.md)
---------------------------------
For each of Lanyon's 72 specifications and each coordinate direction (144
tasks): are the listed wave speeds the eigenvalues of the Jacobian of the
specification's own flux (C1), and is the solver's dissipation speed amax at
least the spectral radius at both interface states (C2)? The frozen judge
(judge.py, built on specs.py) decides both with exact eigenvalues.

The experiment
--------------
experiment.py defines search(info, kit, seed) and returns at most 20 interface
points for one task, aiming at the smallest ratio r = amax / spectral radius.
kit.py offers the pre-registered sampler and a budgeted double-precision
check (4,000 calls per task). The harness re-evaluates every returned point
itself and confirms the three smallest ratios with exact eigenvalues.

Score of a run: V = number of tasks with a confirmed C2 violation; S = sum over
those tasks of (1 - smallest confirmed r). Larger is better.

Commands
--------
    python lab/lanyon_audit/harness.py fingerprint
    python lab/lanyon_audit/harness.py describe
    python lab/lanyon_audit/harness.py census [--seed dev] [--tasks TEXT]      # free
    python lab/lanyon_audit/harness.py probe --experiment lab/lanyon_audit/trials/NAME.py   # free, 14 tasks
    python lab/lanyon_audit/harness.py evaluate --experiment lab/lanyon_audit/trials/NAME.py --note "..."
    python lab/lanyon_audit/harness.py recheck --experiment lab/lanyon_audit/trials/NAME.py --note "..."
    python lab/lanyon_audit/harness.py freeze            # the lab's last step
    python lab/lanyon_audit/harness.py final             # humans, once, after the run
"""
