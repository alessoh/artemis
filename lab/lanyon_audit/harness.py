# ---------------------------------------------------------------- static checks
def docstring_nodes(tree: ast.AST) -> set[int]:
    found = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            body = getattr(node, "body", [])
            if (body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant)
                    and isinstance(body[0].value.value, str)):
                found.add(id(body[0].value))
    return found


def module_allowed(name: str) -> bool:
    parts = name.split(".")
    if parts[0] not in ALLOWED_IMPORTS:
        return False
    return len(parts) == 1 or (len(parts) == 2 and parts[1] in ALLOWED_SUBMODULES.get(parts[0], frozenset()))


def static_check_source(raw: bytes) -> list[str]:
    problems: list[str] = []
    if len(raw) > MAX_EXPERIMENT_BYTES:
        problems.append(f"file is {len(raw)} bytes (limit {MAX_EXPERIMENT_BYTES})")
    try:
        tree = ast.parse(raw.decode("utf-8"))
    except (SyntaxError, UnicodeDecodeError, ValueError) as exc:
        return problems + [f"does not parse: {exc}"]
    docs = docstring_nodes(tree)
    banned = BANNED_NAMES | BANNED_ATTRIBUTES
    numbers, string_chars = 0, 0
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if not module_allowed(alias.name):
                    problems.append(f"import {alias.name}")
        elif isinstance(node, ast.ImportFrom):
            if node.level or not module_allowed(node.module or ""):
                problems.append(f"from {'.' * node.level}{node.module or ''} import")
            for alias in node.names:
                if alias.name == "*":
                    problems.append("import *")
                elif alias.name in banned or alias.name.startswith("_"):
                    problems.append(f"import of {alias.name}")
                elif node.module in ALLOWED_SUBMODULES and alias.name not in ALLOWED_SUBMODULES[node.module]:
                    try:
                        import importlib.util
                        if importlib.util.find_spec(f"{node.module}.{alias.name}") is not None:
                            problems.append(f"from {node.module} import {alias.name} (a submodule not on the list)")
                    except (ImportError, ValueError, AttributeError):
                        pass
        elif isinstance(node, ast.Name):
            if node.id in banned or (node.id.startswith("__") and node.id != "__name__"):
                problems.append(f"name {node.id}")
        elif isinstance(node, ast.Attribute):
            if node.attr in BANNED_ATTRIBUTES or node.attr.startswith("_"):
                problems.append(f"attribute .{node.attr}")
        elif isinstance(node, (ast.List, ast.Tuple, ast.Set)):
            if len(node.elts) > MAX_LITERAL_ELEMENTS:
                problems.append(f"a literal with {len(node.elts)} elements (limit {MAX_LITERAL_ELEMENTS})")
        elif isinstance(node, ast.Dict):
            if len(node.keys) > MAX_LITERAL_ELEMENTS:
                problems.append(f"a dict literal with {len(node.keys)} entries (limit {MAX_LITERAL_ELEMENTS})")
        elif isinstance(node, ast.Constant):
            value = node.value
            if isinstance(value, (int, float, complex)) and not isinstance(value, bool):
                numbers += 1
                if isinstance(value, int) and abs(value) > MAX_INT_MAGNITUDE:
                    problems.append("an integer constant larger than 2**63")
            elif isinstance(value, bytes):
                problems.append("a bytes constant")
            elif isinstance(value, str) and id(node) not in docs:
                string_chars += len(value)
                if len(value) > MAX_STRING_CONSTANT:
                    problems.append(f"a string constant of {len(value)} characters (limit {MAX_STRING_CONSTANT})")
                if "__" in value:
                    problems.append("a string containing a double underscore")
    if numbers > MAX_NUMERIC_CONSTANTS:
        problems.append(f"{numbers} numeric constants (limit {MAX_NUMERIC_CONSTANTS})")
    if string_chars > MAX_STRING_CHARS:
        problems.append(f"{string_chars} characters of string constants (limit {MAX_STRING_CHARS})")
    funcs = [n.name for n in tree.body if isinstance(n, ast.FunctionDef)]
    if "search" not in funcs:
        problems.append("the file must define search(info, kit, seed)")
    return sorted(set(problems))


# ---------------------------------------------------------------- running an experiment
def children_cpu() -> float:
    if resource is None:
        return 0.0
    usage = resource.getrusage(resource.RUSAGE_CHILDREN)
    return usage.ru_utime + usage.ru_stime


def kill_group(proc: subprocess.Popen) -> None:
    try:
        if os.name == "posix":
            os.killpg(proc.pid, signal.SIGKILL)
        else:  # pragma: no cover
            proc.kill()
    except (ProcessLookupError, PermissionError, OSError):
        pass
    try:
        proc.wait(10)
    except subprocess.TimeoutExpired:  # pragma: no cover
        pass


def _limit_memory() -> None:
    if resource is not None:
        resource.setrlimit(resource.RLIMIT_AS, (MEMORY_LIMIT_BYTES, MEMORY_LIMIT_BYTES))


def runner_env() -> dict[str, str]:
    env = {"OMP_NUM_THREADS": "1", "OPENBLAS_NUM_THREADS": "1", "MKL_NUM_THREADS": "1",
           "NUMEXPR_NUM_THREADS": "1", "PYTHONHASHSEED": "0"}
    for name in ("PATH", "SYSTEMROOT", "WINDIR", "TEMP", "TMP", "TMPDIR", "LANG", "LC_ALL"):
        if name in os.environ:
            env[name] = os.environ[name]
    return env


def search_seed(seed: str, name: str) -> int:
    """The integer seed a search receives for a task: domain-separated from the census stream, so
    that a search cannot regenerate the census points (the seed string never reaches the runner)."""
    return int(hashlib.sha256(f"{seed}|search|{name}".encode("utf-8")).hexdigest()[:15], 16)


def run_experiment(source: bytes, names: list[str], seed: str, time_limit: float) -> tuple[list[dict], float, float]:
    token = secrets.token_hex(16)
    message = json.dumps({"token": token, "tasks": names, "task_seeds": [search_seed(seed, n) for n in names],
                          "root": str(LANYON_ROOT)}).encode()
    lines: queue.Queue = queue.Queue()
    prefix = token.encode("ascii") + b" "
    answers: list[dict] = []
    with tempfile.TemporaryDirectory() as tmp:
        code_path = Path(tmp) / "experiment_under_test.py"
        code_path.write_bytes(source)
        with open(Path(tmp) / "stderr.txt", "w+b") as stderr:
            cpu_before = children_cpu()
            extra = {"start_new_session": True, "preexec_fn": _limit_memory} if os.name == "posix" else {}
            started_at = time.monotonic()
            proc = subprocess.Popen([sys.executable, "-I", str(RUNNER), str(code_path)], stdin=subprocess.PIPE,
                                    stdout=subprocess.PIPE, stderr=stderr, cwd=tmp, env=runner_env(), **extra)

            def reader() -> None:
                assert proc.stdout is not None
                for raw in proc.stdout:
                    if raw.startswith(prefix):
                        kind, _, payload = raw[len(prefix):].decode("utf-8", "replace").partition(" ")
                        lines.put((time.monotonic(), kind.strip(), payload))
                lines.put((time.monotonic(), "EOF", ""))

            def writer() -> None:
                try:
                    assert proc.stdin is not None
                    proc.stdin.write(message)
                    proc.stdin.close()
                except (BrokenPipeError, OSError):
                    pass

            threading.Thread(target=reader, daemon=True).start()
            threading.Thread(target=writer, daemon=True).start()
            ready_at, done_at = None, None
            try:
                deadline = time.monotonic() + READY_TIMEOUT_S
                while True:
                    remaining = deadline - time.monotonic()
                    if remaining <= 0:
                        if ready_at is None:
                            raise HarnessError("the experiment did not start in time; the run was stopped.")
                        raise HarnessError(f"the experiment did not finish within {time_limit:.0f} s; "
                                           "the run was stopped.")
                    try:
                        stamp, kind, payload = lines.get(timeout=remaining)
                    except queue.Empty:
                        continue
                    if kind == "READY" and ready_at is None:
                        ready_at = stamp
                        deadline = stamp + time_limit
                    elif kind == "POINTS":
                        answers.append(json.loads(payload))
                    elif kind == "DONE":
                        done_at = stamp
                        break
                    elif kind == "ERROR":
                        try:
                            detail = json.loads(payload)
                        except ValueError:
                            detail = payload
                        raise HarnessError(f"search() raised an error:\n{detail}")
                    elif kind == "EOF":
                        stderr.seek(0)
                        tail = stderr.read()[-1500:].decode("utf-8", "replace")
                        raise HarnessError(f"the experiment process ended without finishing.\n{tail}")
            finally:
                kill_group(proc)
            cpu = children_cpu() - cpu_before
    wall = done_at - started_at
    if resource is not None and cpu > CPU_FACTOR * wall + CPU_GRACE_S:
        raise HarnessError(f"used {cpu:.0f} CPU seconds in {wall:.0f} s of wall time; experiments must use one core.")
    if [a["task"] for a in answers] != names:
        raise HarnessError("the experiment did not answer every task in order.")
    return answers, round(done_at - ready_at, 1), round(cpu, 1)


# ---------------------------------------------------------------- scoring
def score_task(task: judge.Task, points: list[dict]) -> dict:
    """Re-evaluate every returned point; confirm the smallest ratios with exact eigenvalues."""
    evaluated, outside = [], 0
    for p in points:
        try:
            e = judge.evaluate_point(task, p)
        except judge.Inadmissible:
            continue
        if not judge.in_box(task, e["point"]):
            outside += 1
            continue
        evaluated.append(e)
    out = {"task": task.name, "returned": len(points), "admissible": len(evaluated), "outside_box": outside,
           "violation": False, "min_ratio": None, "worst_point": None, "c1_found": False, "unconfirmable": 0}
    got = 0
    for e in sorted(evaluated, key=lambda e: e["ratio"]):
        if got >= CONFIRM_RETURNED:
            break
        try:
            c = judge.confirm_point(task, e["point"])
        except judge.Inadmissible:
            out["unconfirmable"] += 1
            continue
        got += 1
        out["c1_found"] |= c["c1_fails"]
        if c["c2_fails"]:
            out["violation"] = True
        if out["min_ratio"] is None or c["ratio"] < out["min_ratio"]:
            out["min_ratio"], out["worst_point"] = c["ratio"], e["point"]
    return out


def summarise(rows: list[dict]) -> dict:
    viol = [r for r in rows if r["violation"]]
    S = sum(max(0.0, 1.0 - r["min_ratio"]) for r in viol)
    fam: dict[str, dict] = {}
    for r in rows:
        f = fam.setdefault(r["task"].split("/")[0], {"tasks": 0, "V": 0, "S": 0.0, "min_ratio": None})
        f["tasks"] += 1
        if r["violation"]:
            f["V"] += 1
            f["S"] += max(0.0, 1.0 - r["min_ratio"])
        if r["min_ratio"] is not None:
            f["min_ratio"] = r["min_ratio"] if f["min_ratio"] is None else min(f["min_ratio"], r["min_ratio"])
    return {"S": round(S, 6), "V": len(viol), "tasks": len(rows), "by_family": fam,
            "violating_tasks": sorted(r["task"] for r in viol)}


# ---------------------------------------------------------------- ledger
@contextlib.contextmanager
def eval_lock():
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    if fcntl is None:
        yield
        return
    with open(LOCK, "w") as handle:
        try:
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            print("Another evaluation is running; waiting for it to finish ...", flush=True)
            fcntl.flock(handle, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)


def git_commit() -> str:
    try:
        return subprocess.run(["git", "-C", str(REPO_ROOT), "rev-parse", "--short", "HEAD"], capture_output=True,
                              text=True, timeout=10).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return ""


def read_ledger() -> list[dict[str, str]]:
    if not LEDGER.exists():
        return []
    with open(LEDGER, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def append_ledger(row: dict) -> None:
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    new = not LEDGER.exists()
    with open(LEDGER, "a", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=LEDGER_FIELDS, delimiter="\t", extrasaction="ignore")
        if new:
            writer.writeheader()
        writer.writerow({k: str(row.get(k, "")).replace("\t", " ").replace("\n", " ") for k in LEDGER_FIELDS})


def relative(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def base_row(kind: str, seed: str, label: str, sha12: str, note: str) -> dict:
    prints = fingerprint()
    return {"utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "kind": kind, "seed": seed,
            "experiment": label, "experiment_sha12": sha12, "git_commit": git_commit(),
            "harness_sha12": prints["harness"][:12], "data_sha12": prints["data"][:12], "note": note}


def save_details(row: dict, summary: dict, rows: list[dict], source: bytes | None) -> None:
    DETAILS_DIR.mkdir(parents=True, exist_ok=True)
    stem = (f"{row['utc'].replace(':', '')}_{row['kind']}_{Path(str(row['experiment'])).stem}"
            f"_{row.get('experiment_sha12') or 'none'}_{row['seed']}_{uuid.uuid4().hex[:8]}")
    if source is not None:
        (DETAILS_DIR / f"{stem}.code.txt").write_bytes(source)
    with open(DETAILS_DIR / f"{stem}.json", "x", encoding="utf-8") as handle:
        handle.write(json.dumps({"row": row, "summary": summary, "tasks": rows}) + "\n")


def saved_summary(sha12: str, seed: str) -> dict | None:
    if not DETAILS_DIR.exists():
        return None
    found = None
    for path in sorted(DETAILS_DIR.glob("*.json")):
        record = json.loads(path.read_text(encoding="utf-8"))
        row = record["row"]
        if row.get("experiment_sha12") == sha12 and row.get("seed") == seed and row.get("status") == "ok" \
                and row.get("kind") in ("experiment", "recheck"):
            found = record["summary"]
    return found


def started(kind: str) -> int:
    return sum(1 for r in read_ledger() if r["kind"] == kind and r["status"] == "started")


def load_source(path: Path, kind: str, seed: str, note: str) -> bytes:
    if not path.exists():
        raise HarnessError(f"No file at {path}")
    source = path.read_bytes()
    problems = static_check_source(source)
    if problems:
        row = base_row(kind, seed, relative(path), hashlib.sha256(source).hexdigest()[:12], note)
        row.update(status="refused", note=f"{note} | refused: {'; '.join(problems)}"[:500])
        with eval_lock():
            append_ledger(row)
        raise HarnessError("Refused: " + "; ".join(problems) + ". See the rules in program.md.")
    return source


def run_and_score(source: bytes, names: list[str], seed: str, limit: float) -> tuple[dict, list[dict], float, float]:
    answers, seconds, cpu = run_experiment(source, names, seed, limit)
    tasks = all_tasks()
    rows = []
    for a in answers:
        r = score_task(tasks[a["task"]], a["points"])
        r.update(calls=a["calls"], cpu=a["cpu"])
        rows.append(r)
    return summarise(rows), rows, seconds, cpu


def evaluate(path: Path, kind: str, seed: str, note: str, budget: int) -> tuple[dict, dict]:
    source = load_source(path, kind, seed, note)
    sha12 = hashlib.sha256(source).hexdigest()[:12]
    with eval_lock():
        if started(kind) >= budget:
            raise HarnessError(f"The {kind} budget of {budget} is used up.")
        row = base_row(kind, seed, relative(path), sha12, note)
        append_ledger({**row, "status": "started"})
        try:
            summary, rows, seconds, cpu = run_and_score(source, list(all_tasks()), seed, TIME_LIMIT_S["full"])
        except HarnessError as exc:
            row.update(status="invalid", note=f"{note} | {exc}"[:500])
            append_ledger(row)
            raise
        row.update(S=summary["S"], V=summary["V"], tasks=summary["tasks"], seconds=seconds, cpu_seconds=cpu,
                   status="ok")
        if DEFAULT_EXPERIMENT.exists():
            best_sha = sha256_file(DEFAULT_EXPERIMENT)[:12]
            best = saved_summary(best_sha, EVAL_SEED)
            if best is None:
                print("NOTE: no saved eval-1 result for the current experiment.py, so no comparison "
                      "(evaluate it first).", flush=True)
            else:
                row.update(delta_S=round(summary["S"] - best["S"], 6), delta_V=summary["V"] - best["V"])
        append_ledger(row)
        save_details(row, summary, rows, source)
    return row, summary


