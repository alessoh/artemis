"""Frozen kit: what an experiment's search() may call for one task.

DO NOT EDIT THIS FILE. It is part of the harness fingerprint.

An experiment defines search(info, kit, seed) and returns a list of at most
MAX_POINTS interface points for one (specification, direction) task. A point
is a dict {"L": [...], "R": [...], "P": [...], "X": [...]} with the left and
right states (in the order of info["state"]), the parameters (info["parameters"])
and the coordinates (info["coordinates"], shared by both sides).

The harness, not the kit, decides the score: it re-evaluates every returned
point itself and confirms the lowest ratios with exact eigenvalues.

kit.info            the task: names, assumptions, flux and speed formulas
kit.sample(rng)     a point from the pre-registered baseline sampler (free)
kit.evaluate(p)     double-precision check of a point (costs one call):
                    {"ratio", "amax", "rho", "c1"} or None if p is not admissible
                    or lies outside the box (kit.in_box)
kit.in_box(p)       True when p lies in the census sampling box (free): every
                    value at most 10 in magnitude; variables declared positive
                    at least 1e-2; any other value 0 or at least 1e-2 in
                    magnitude. The harness scores only points in the box.
kit.side(s, P, X)   one state (costs one call): {"listed", "eigenvalues", "rho"}
                    or None if not admissible
kit.calls, kit.remaining()   calls used and left (budget CALL_BUDGET per task)
"""
from __future__ import annotations

import numpy as np

import judge

CALL_BUDGET = 4000
MAX_POINTS = 20


class Kit:
    def __init__(self, task: judge.Task):
        self._task = task
        self.info = task.info()
        self.calls = 0
        self.budget = CALL_BUDGET

    def remaining(self) -> int:
        return max(0, self.budget - self.calls)

    def _spend(self) -> bool:
        if self.calls >= self.budget:
            return False
        self.calls += 1
        return True

    def sample(self, rng: np.random.Generator) -> dict:
        return judge.sample_point(self._task, rng)

    def evaluate(self, point: dict) -> dict | None:
        if not self._spend():
            return None
        try:
            r = judge.evaluate_point(self._task, point)
        except judge.Inadmissible:
            return None
        if not judge.in_box(self._task, r["point"]):
            return None
        return {"ratio": r["ratio"], "amax": r["amax"], "rho": r["rho"], "c1": r["c1"]}

    def in_box(self, point: dict) -> bool:
        try:
            return judge.in_box(self._task, judge.validate_point(self._task, point))
        except judge.Inadmissible:
            return False

    def side(self, state, P, X) -> dict | None:
        if not self._spend():
            return None
        try:
            p = judge.validate_point(self._task, {"L": state, "R": state, "P": P, "X": X})
            judge._check_assumptions(self._task, p)
            listed, ev, rho = judge.side_values(self._task, p["L"], p["P"], p["X"])
        except judge.Inadmissible:
            return None
        return {"listed": sorted(listed), "eigenvalues": [float(e) for e in ev], "rho": rho}
