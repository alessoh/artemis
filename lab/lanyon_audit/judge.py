"""Frozen judge for the Lanyon wave-speed audit.

DO NOT EDIT THIS FILE. It is part of the harness fingerprint.

For every (specification, direction) task this module compiles, from the exact
SymPy model built by specs.py:
  * the listed wave speeds and the flux Jacobian at one state, and
  * the solver's two speeds at an interface (left state, right state),
both in double precision (Python's math module) and in 50-digit arithmetic
(mpmath). It implements the definitions fixed in preregistration.md:

  interface point   {"L": [...], "R": [...], "P": [...], "X": [...]}: left and
                    right states (in the specification's variable order), the
                    parameters and the coordinates (shared by both sides).
  baseline sampler  sign uniform, magnitude log-uniform on [1e-2, 1e1] for
                    every state variable (each side), parameter and coordinate;
                    variables declared > 0 or >= 0 drawn positive; draws that
                    break a declared assumption are rejected.
  admissible        listed speeds and solver speeds finite and real on both
                    sides; every Jacobian eigenvalue real (imaginary part at
                    most 1e-9 (1 + spectral radius)); spectral radius at least
                    1e-8 on one side.
  C1 mismatch       sorted listed speeds and sorted eigenvalues differ by more
                    than 1e-12 (1 + spectral radius) on a side, at 50 digits.
  C2 violation      amax < (1 - 1e-12) max(rho_L, rho_R) at 50 digits, where
                    amax is the larger magnitude of the solver's two speeds;
                    the ratio r = amax / max(rho_L, rho_R) is reported.

The census draws 400 admissible points per task (at most 400,000 draws) and
re-evaluates at 50 digits the five points with the largest double-precision
C1 discrepancy and the five with the smallest ratio.
"""
