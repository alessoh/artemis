LOG10_MIN, LOG10_MAX = -2.0, 1.0
IMAG_TOL = 1e-9
RHO_MIN = 1e-8
C1_TOL = 1e-12
C2_TOL = 1e-12
MP_DIGITS = 50
CENSUS_POINTS = 400
CENSUS_MAX_DRAWS = 400_000
CONFIRM_TOP = 5


class Inadmissible(Exception):
    """The point is outside the region the definitions cover."""


def _lam(args, exprs, module):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return sp.lambdify(args, exprs, modules=module, cse=True)


@dataclass
class Task:
    name: str
    spec: specs.SpecModel
    d: int
    listed: object          # (state, params, coords) -> list
    jac: object             # (state, params, coords) -> nested list
    speeds: object          # (L, R, params, XL, XR) -> [s1, s2]
    s_assume: list          # (state) -> bool, one per assumption
    p_assume: list          # (params) -> bool
    _mp: dict | None = None

    @property
    def n_state(self) -> int:
        return len(self.spec.state)

    def info(self) -> dict:
        s = self.spec
        return {"name": self.name, "family": s.family, "spec": s.name, "direction": s.coordinates[self.d],
                "state": list(s.state), "parameters": list(s.parameters), "coordinates": list(s.coordinates),
                "positive": sorted(s.positive),
                "state_assumptions": [str(a) for a in s.state_assumptions],
                "parameter_assumptions": [str(a) for a in s.parameter_assumptions],
                "flux": [str(e) for e in s.flux[self.d]],
                "listed_speeds": [str(e) for e in s.listed[self.d]],
                "solver_speeds": [str(e) for e in s.speeds[self.d]], "solver": s.solver}

    def mp(self) -> dict:
        if self._mp is None:
            s, d = self.spec, self.d
            st = [specs.symbol(n) for n in s.state]
            pa = [specs.symbol(n) for n in s.parameters]
            co = [specs.symbol(n) for n in s.coordinates]
            L = [specs.symbol(f"{n}_L") for n in s.state]
            R = [specs.symbol(f"{n}_R") for n in s.state]
            XL = [specs.symbol(f"{n}_L") for n in s.coordinates]
            XR = [specs.symbol(f"{n}_R") for n in s.coordinates]
            J = sp.Matrix(s.flux[d]).jacobian(st)
            if any(not e.is_rational_function(*(st + pa + co)) for e in J):
                raise specs.SpecError(f"{self.name}: the flux Jacobian is not rational; exact confirmation needs it")
            self._mp = {"listed": _lam([st, pa, co], s.listed[d], "mpmath"),
                        "jac_sym": J, "args": st + pa + co,
                        "speeds": _lam([L, R, pa, XL, XR], s.speeds[d], "mpmath")}
        return self._mp


def compile_spec(model: specs.SpecModel) -> list[Task]:
    st = [specs.symbol(n) for n in model.state]
    pa = [specs.symbol(n) for n in model.parameters]
    co = [specs.symbol(n) for n in model.coordinates]
    L = [specs.symbol(f"{n}_L") for n in model.state]
    R = [specs.symbol(f"{n}_R") for n in model.state]
    XL = [specs.symbol(f"{n}_L") for n in model.coordinates]
    XR = [specs.symbol(f"{n}_R") for n in model.coordinates]
    s_assume = [_lam([st], a, "math") for a in model.state_assumptions]
    p_assume = [_lam([pa], a, "math") for a in model.parameter_assumptions]
    for a in model.state_assumptions:
        if a.free_symbols - set(st):
            raise specs.SpecError(f"{model.name}: a state assumption uses non-state names: {a}")
    for a in model.parameter_assumptions:
        if a.free_symbols - set(pa):
            raise specs.SpecError(f"{model.name}: a parameter assumption uses non-parameter names: {a}")
    tasks = []
    for d in range(model.directions):
        J = sp.Matrix(model.flux[d]).jacobian(st)
        tasks.append(Task(name=model.task_names()[d], spec=model, d=d,
                          listed=_lam([st, pa, co], model.listed[d], "math"),
                          jac=_lam([st, pa, co], J.tolist(), "math"),
                          speeds=_lam([L, R, pa, XL, XR], model.speeds[d], "math"),
                          s_assume=s_assume, p_assume=p_assume))
    return tasks


def spec_files(root: Path) -> list[tuple[str, Path]]:
    out = []
    for family in FAMILIES:
        folder = Path(root) / family / "specifications"
        files = sorted(folder.glob("*.rkt"))
        if not files:
            raise FileNotFoundError(f"no specifications in {folder}")
        out += [(family, f) for f in files]
    return out


def load_tasks(root: Path) -> list[Task]:
    tasks = []
    for family, path in spec_files(root):
        tasks += compile_spec(specs.load_spec(path, family))
    return tasks


# ------------------------------------------------------------------ evaluation
BOX_MAX = 10.0 ** LOG10_MAX
BOX_MIN = 10.0 ** LOG10_MIN


def in_box(task: Task, point: dict) -> bool:
    """The census sampling box, used to score searches (IMPLEMENTATION_NOTES.md): every value has
    magnitude at most 10; a variable declared positive is at least 1e-2; any other value is either
    exactly 0 or has magnitude at least 1e-2."""
    s = task.spec
    named = ([(n, v) for side in ("L", "R") for n, v in zip(s.state, point[side])]
             + list(zip(s.parameters, point["P"])) + list(zip(s.coordinates, point["X"])))
    for name, v in named:
        a = abs(v)
        if a > BOX_MAX:
            return False
        if name in s.positive:
            if v < BOX_MIN:
                return False
        elif v != 0.0 and a < BOX_MIN:
            return False
    return True


def _real(x) -> float:
    if isinstance(x, complex):
        if x.imag != 0:
            raise Inadmissible("complex value")
        x = x.real
    x = float(x)
    if not math.isfinite(x):
        raise Inadmissible("non-finite value")
    return x


def _check_assumptions(task: Task, point: dict) -> None:
    for f in task.p_assume:
        if not bool(f(point["P"])):
            raise Inadmissible("parameter assumption fails")
    for side in ("L", "R"):
        for f in task.s_assume:
            if not bool(f(point[side])):
                raise Inadmissible("state assumption fails")


def validate_point(task: Task, point) -> dict:
    """Normalise a point to the expected shape (lists of finite floats)."""
    if not isinstance(point, dict):
        raise Inadmissible("a point must be a dict with keys L, R, P, X")
    s = task.spec
    sizes = {"L": len(s.state), "R": len(s.state), "P": len(s.parameters), "X": len(s.coordinates)}
    out = {}
    for key, n in sizes.items():
        v = point.get(key, [])
        try:
            v = [float(x) for x in v]
        except (TypeError, ValueError):
            raise Inadmissible(f"{key} must be a list of numbers") from None
        if len(v) != n:
            raise Inadmissible(f"{key} must have {n} entries")
        if not all(math.isfinite(x) for x in v):
            raise Inadmissible(f"{key} has a non-finite entry")
        out[key] = v
    return out


def side_values(task: Task, state, P, X) -> tuple[list[float], np.ndarray, float]:
    try:
        listed = [_real(v) for v in task.listed(state, P, X)]
        J = np.array([[_real(v) for v in row] for row in task.jac(state, P, X)], dtype=float)
    except (ValueError, ZeroDivisionError, OverflowError) as exc:
        raise Inadmissible(f"evaluation failed: {type(exc).__name__}") from None
    if not np.all(np.isfinite(J)):
        raise Inadmissible("non-finite Jacobian")
    ev = np.linalg.eigvals(J)
    rho = float(np.max(np.abs(ev))) if ev.size else 0.0
    if np.max(np.abs(ev.imag)) > IMAG_TOL * (1.0 + rho):
        raise Inadmissible("complex eigenvalues")
    return listed, np.sort(ev.real), rho


def evaluate_point(task: Task, point) -> dict:
    """Double-precision evaluation. Raises Inadmissible outside the covered region."""
    point = validate_point(task, point)
    _check_assumptions(task, point)
    P, X = point["P"], point["X"]
    lL, eL, rL = side_values(task, point["L"], P, X)
    lR, eR, rR = side_values(task, point["R"], P, X)
    rho = max(rL, rR)
    if rho < RHO_MIN:
        raise Inadmissible("spectral radius below 1e-8")
    try:
        s = [_real(v) for v in task.speeds(point["L"], point["R"], P, X, X)]
    except (ValueError, ZeroDivisionError, OverflowError) as exc:
        raise Inadmissible(f"solver speeds failed: {type(exc).__name__}") from None
    amax = max(abs(s[0]), abs(s[1]))
    c1 = max(float(np.max(np.abs(np.sort(lL) - eL))) / (1 + rL) if eL.size else 0.0,
             float(np.max(np.abs(np.sort(lR) - eR))) / (1 + rR) if eR.size else 0.0)
    return {"ratio": amax / rho, "amax": amax, "rho": rho, "c1": c1, "point": point}


def _mp_real(x):
    if isinstance(x, mpmath.mpc):
        if abs(x.imag) > mpmath.mpf(10) ** (-(MP_DIGITS - 5)) * (1 + abs(x.real)):
            raise Inadmissible("complex value at 50 digits")
        return x.real
    return mpmath.mpf(x)


_T = sp.Symbol("t")


def exact_eigenvalues(task: Task, state, P, X) -> list:
    """Eigenvalues of the flux Jacobian, exactly: the inputs are binary64 numbers, hence exact
    rationals; every flux is a rational function, so the Jacobian is an exact rational matrix;
    its characteristic polynomial is computed over the rationals and its real roots are
    isolated exactly, with multiplicity, then evaluated to MP_DIGITS + 10 digits."""
    f = task.mp()
    values = [sp.Rational(float(v)) for v in list(state) + list(P) + list(X)]   # exact binary values
    J = f["jac_sym"].xreplace(dict(zip(f["args"], values)))
    if not all(e.is_Rational for e in J):
        raise Inadmissible("the Jacobian did not evaluate to exact rationals")
    poly = sp.Poly(J.charpoly(_T).as_expr(), _T, domain="QQ")
    roots = sp.real_roots(poly)
    if len(roots) != poly.degree():
        raise Inadmissible("complex eigenvalues (exact)")
    return sorted(mpmath.mpf(str(sp.N(r, MP_DIGITS + 10))) for r in roots)


def confirm_point(task: Task, point) -> dict:
    """C1 and C2 at a point with exact eigenvalues and 50-digit speeds (preregistration.md)."""
    point = validate_point(task, point)
    _check_assumptions(task, point)
    f = task.mp()
    with mpmath.workdps(MP_DIGITS):
        P = [mpmath.mpf(v) for v in point["P"]]
        X = [mpmath.mpf(v) for v in point["X"]]
        sides = {}
        for side in ("L", "R"):
            st = [mpmath.mpf(v) for v in point[side]]
            listed = sorted(_mp_real(v) for v in f["listed"](st, P, X))
            real_ev = exact_eigenvalues(task, point[side], point["P"], point["X"])
            rho = max(abs(e) for e in real_ev)
            mism = max(abs(a - b) for a, b in zip(listed, real_ev)) / (1 + rho)
            sides[side] = (rho, mism)
        s = [_mp_real(v) for v in f["speeds"]([mpmath.mpf(v) for v in point["L"]],
                                              [mpmath.mpf(v) for v in point["R"]], P, X, X)]
        amax = max(abs(s[0]), abs(s[1]))
        rho = max(sides["L"][0], sides["R"][0])
        mism = max(sides["L"][1], sides["R"][1])
        return {"ratio": float(amax / rho), "c1_mismatch": float(mism),
                "c1_fails": bool(mism > C1_TOL), "c2_fails": bool(amax < (1 - mpmath.mpf(C2_TOL)) * rho),
                "amax": float(amax), "rho": float(rho)}


# ------------------------------------------------------------------ sampling and census
def task_rng(seed: str, task_name: str) -> np.random.Generator:
    digest = hashlib.sha256(f"{seed}|{task_name}".encode("utf-8")).hexdigest()
    return np.random.default_rng(int(digest[:16], 16))


def sample_point(task: Task, rng: np.random.Generator, fixed: dict | None = None) -> dict:
    """The pre-registered baseline sampler. `fixed` (exploratory analyses only) pins
    named parameters after the draw, e.g. {"c": 1.0}."""
    s = task.spec

    def draw(names):
        mags = 10.0 ** rng.uniform(LOG10_MIN, LOG10_MAX, len(names))
        signs = np.where(rng.random(len(names)) < 0.5, -1.0, 1.0)
        return [float(m if n in s.positive else m * g) for n, m, g in zip(names, mags, signs)]

    point = {"L": draw(s.state), "R": draw(s.state), "P": draw(s.parameters), "X": draw(s.coordinates)}
    for name, value in (fixed or {}).items():
        if name in s.parameters:
            point["P"][s.parameters.index(name)] = float(value)
    return point


def census_task(task: Task, seed: str, n_points: int = CENSUS_POINTS, max_draws: int = CENSUS_MAX_DRAWS,
                fixed: dict | None = None) -> dict:
    rng = task_rng(seed if not fixed else f"{seed}|fixed={sorted(fixed.items())}", task.name)
    accepted, draws, reasons = [], 0, {}
    while len(accepted) < n_points and draws < max_draws:
        draws += 1
        p = sample_point(task, rng, fixed)
        try:
            accepted.append(evaluate_point(task, p))
        except Inadmissible as exc:
            reasons[str(exc)] = reasons.get(str(exc), 0) + 1
    out = {"task": task.name, "family": task.spec.family, "spec": task.spec.name, "accepted": len(accepted),
           "draws": draws, "rejections": reasons, "c1_fails": False, "c2_fails": False,
           "min_ratio_float": None, "min_ratio_confirmed": None, "worst_point": None, "max_c1_float": None,
           "max_c1_confirmed": None, "c2_violations_float": 0}
    if not accepted:
        return out
    out["min_ratio_float"] = min(a["ratio"] for a in accepted)
    out["max_c1_float"] = max(a["c1"] for a in accepted)
    out["c2_violations_float"] = sum(1 for a in accepted if a["ratio"] < 1 - 1e-9)
    out["unconfirmable"] = 0

    def confirmed(candidates):
        """Confirm candidates in order until CONFIRM_TOP succeed (a point whose exact
        eigenvalues turn out complex is skipped and counted as unconfirmable)."""
        got = []
        for a in candidates:
            if len(got) >= CONFIRM_TOP:
                break
            try:
                got.append((a, confirm_point(task, a["point"])))
            except Inadmissible:
                out["unconfirmable"] += 1
        return got

    c1_res = confirmed(sorted(accepted, key=lambda a: -a["c1"]))
    ratio_res = confirmed(sorted(accepted, key=lambda a: a["ratio"]))
    for _, c in c1_res + ratio_res:
        out["c1_fails"] |= c["c1_fails"]
    best = None
    for a, c in ratio_res:
        out["c2_fails"] |= c["c2_fails"]
        if best is None or c["ratio"] < best[0]:
            best = (c["ratio"], a["point"])
    if c1_res:
        out["max_c1_confirmed"] = max(c["c1_mismatch"] for _, c in c1_res)
    if best is not None:
        out["min_ratio_confirmed"] = best[0]
        out["worst_point"] = best[1]
    return out


def classify(results: list[dict]) -> dict[str, dict]:
    """Per specification: fails C1 / C2 if any of its tasks does."""
    by: dict[str, dict] = {}
    for r in results:
        key = f"{r['family']}/{r['spec']}"
        e = by.setdefault(key, {"family": r["family"], "spec": r["spec"], "c1_fails": False, "c2_fails": False,
                                "tasks": 0, "min_ratio": None, "all_covered": True})
        e["tasks"] += 1
        e["c1_fails"] |= r["c1_fails"]
        e["c2_fails"] |= r["c2_fails"]
        e["all_covered"] &= r["accepted"] >= CENSUS_POINTS
        if r["min_ratio_confirmed"] is not None:
            e["min_ratio"] = r["min_ratio_confirmed"] if e["min_ratio"] is None else min(e["min_ratio"],
                                                                                          r["min_ratio_confirmed"])
    return by


# ------------------------------------------------------------------ predictions (preregistration.md)
def prediction_for(family: str, spec: str) -> tuple[str, bool, bool]:
    """(prediction id, predicted C1 failure, predicted C2 failure)."""
    if family == "IdealMHD":
        return "P1", True, True
    if family == "MaxwellEquations" and spec.startswith("hyperbolic_maxwell"):
        return "P2", False, True
    if family == "GeneralRelativisticMaxwell" and spec.startswith("gr_hyperbolic_maxwell"):
        return "P3", False, True
    return "P4", False, False


def score_predictions(by_spec: dict[str, dict]) -> dict:
    out = {}
    for key, e in sorted(by_spec.items()):
        pid, p1, p2 = prediction_for(e["family"], e["spec"])
        ok = (e["c1_fails"] == p1) and (e["c2_fails"] == p2)
        rec = out.setdefault(pid, {"specs": 0, "matching": 0, "mismatches": []})
        rec["specs"] += 1
        rec["matching"] += int(ok)
        if not ok:
            rec["mismatches"].append({"spec": key, "observed_c1_fails": e["c1_fails"],
                                      "observed_c2_fails": e["c2_fails"], "predicted_c1_fails": p1,
                                      "predicted_c2_fails": p2})
    for rec in out.values():
        rec["confirmed"] = rec["matching"] == rec["specs"]
    return out


