def save_details(row: dict, scores: np.ndarray, source: bytes | None = None) -> None:
    """Keep every class's score and the exact code that ran, so anything can be re-checked."""
    DETAILS_DIR.mkdir(parents=True, exist_ok=True)
    stem = (f"{row['utc'].replace(':', '')}_{row['kind']}_{row['split']}_{Path(str(row['experiment'])).stem}"
            f"_{row.get('experiment_sha12') or 'none'}_s{row['seeds']}_{uuid.uuid4().hex[:8]}")
