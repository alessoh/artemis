        writer = csv.DictWriter(handle, fieldnames=LEDGER_FIELDS, delimiter="\t", extrasaction="ignore")
        if new:
            writer.writeheader()
        writer.writerow({k: str(row.get(k, "")).replace("\t", " ").replace("\n", " ")
                         for k in LEDGER_FIELDS})


