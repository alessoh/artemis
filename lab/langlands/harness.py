# ---------------------------------------------------------------- integrity
def sha256_file(path: Path) -> str:
    """Return the hex SHA-256 of the file at *path*."""
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def data_digest() -> str:
    """One SHA-256 over the three frozen data files (in a fixed order)."""
    digest = hashlib.sha256()
    for path in (RANK_SIGNS, MURM_Q, MURM_K, RAW_K):
        digest.update(sha256_file(path).encode("ascii") if path.exists() else b"missing")
    return digest.hexdigest()


def fingerprint() -> dict[str, str]:
    """Return the SHA-256 of the harness, the runner and the data snapshot."""
    return {
        "harness": sha256_file(Path(__file__).resolve()),
        "runner": sha256_file(RUNNER),
        "data": data_digest(),
    }


def check_data() -> dict:
    """Check the frozen snapshot against its manifest and return the manifest."""
    if not MANIFEST.exists() or not all(p.exists() for p in (RANK_SIGNS, MURM_Q, MURM_K)):
        raise HarnessError("The data snapshot is missing. A human builds it once with "
                           "`python lab/langlands/prepare_data.py` and commits lab/langlands/data/.")
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    for path in (RANK_SIGNS, MURM_Q, MURM_K):
        expected = manifest.get("sha256", {}).get(path.name)
        actual = sha256_file(path)
        if actual != expected:
            raise HarnessError(f"{path.name} does not match its manifest (expected "
                               f"{str(expected)[:12]}, found {actual[:12]}). Someone changed the "
                               "data; restore it from git before continuing.")
    raw_expected = manifest.get("sources", {}).get("lmfdb_q_sqrt5", {}).get("sha256")
    if not RAW_K.exists() or sha256_file(RAW_K) != raw_expected:
        raise HarnessError(f"{RAW_K.name} is missing or does not match its manifest; restore it from git.")
    return manifest


