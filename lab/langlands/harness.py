# ---------------------------------------------------------------- Part B data
class RankTable:
    """The rank-0 and rank-2 classes over Q, in file order (by conductor, then class)."""

    def __init__(self) -> None:
        check_data()
        n_list, rank_list, bad_list, ap_list = [], [], [], []
        with gzip.open(RANK_SIGNS, "rt", encoding="ascii") as handle:
            header = handle.readline().rstrip("\n").split("\t")
            if header != ["N", "class", "rank", "bad", "ap25"]:
                raise HarnessError(f"unexpected columns in {RANK_SIGNS.name}: {header}")
            for line in handle:
                n, _, rank, bad, ap = line.rstrip("\n").split("\t")
                n_list.append(int(n))
                rank_list.append(int(rank))
                bad_list.append(bad)
                ap_list.append(ap)
        self.N = np.asarray(n_list, dtype=np.int64)
        self.rank = np.asarray(rank_list, dtype=np.int64)
        self.bad = bad_list
        self.ap25 = ap_list
        # Bit i set when the i-th bad prime (in increasing order) has local sign -1.
        self.mask = np.asarray([sum(1 << k for k, item in enumerate(b.split(";")) if item.endswith("-1"))
                                for b in bad_list], dtype=np.int64)
        if self.mask.max() >= 64:
            raise HarnessError("a conductor with more than six bad primes; the row key needs widening")

    def split(self, name: str) -> np.ndarray:
        """Row indices of a split, in file order."""
        bounds = {"train": (0, TRAIN_MAX_N), "val": (TRAIN_MAX_N, VAL_MAX_N),
                  "test": (VAL_MAX_N, TEST_MAX_N), "probe_fit": (0, PROBE_FIT_MAX_N),
                  "probe_check": (PROBE_FIT_MAX_N, TRAIN_MAX_N)}
        lo, hi = bounds[name]
        return np.flatnonzero((self.N >= lo) & (self.N < hi))

    def signs(self, i: int) -> list[list[int]]:
        """[[p, e, w_p], ...] for row *i*."""
        return [[int(x) for x in item.split(":")] for item in self.bad[i].split(";")]

    def records(self, idx: np.ndarray, with_rank: bool) -> list[dict]:
        """What score() receives: N and the signs, plus the rank for training rows."""
        out = []
        for i in idx:
            rec = {"N": int(self.N[i]), "bad": self.signs(int(i))}
            if with_rank:
                rec["rank"] = int(self.rank[i])
            out.append(rec)
        return out


def split_count_scores(table: RankTable, idx: np.ndarray) -> np.ndarray:
    """Frozen simple rule: how many multiplicative primes have local sign -1 (split)."""
    return np.array([sum(1 for p, e, w in table.signs(int(i)) if e == 1 and w == -1)
                     for i in idx], dtype=np.float64)


def nagao_scores(table: RankTable, idx: np.ndarray) -> np.ndarray:
    """Positive control: sum over good p < 100 of -a_p log(p) / p (uses a_p; experiments never do)."""
    weights = [math.log(p) / p for p in PRIMES_BELOW_100]
    out = np.empty(len(idx))
    for k, i in enumerate(idx):
        total = 0.0
        for wgt, a in zip(weights, table.ap25[int(i)].split(",")):
            if a:
                total -= int(a) * wgt
        out[k] = total
    return out


# ---------------------------------------------------------------- within-conductor statistics
def within_parts(scores: np.ndarray, groups: np.ndarray, positive: np.ndarray) -> dict:
    """Per-conductor pieces of the stratified Wilcoxon (Mann-Whitney) statistic.

    *groups* are conductor labels, *positive* marks rank-2 classes. Only
    conductors with both ranks contribute. Returns per-group U, pairs and
    permutation variance, and per-row midranks within each group.
    """
    scores = np.asarray(scores, dtype=np.float64)
    _, gid = np.unique(groups, return_inverse=True)
    n_groups = int(gid.max()) + 1
    n_pos = np.bincount(gid, weights=positive.astype(np.float64), minlength=n_groups)
    n_all = np.bincount(gid, minlength=n_groups).astype(np.float64)
    mixed = (n_pos > 0) & (n_pos < n_all)
    keep = mixed[gid]
    g, s, y = gid[keep], scores[keep], positive[keep]
    order = np.lexsort((s, g))
    g_sorted, s_sorted = g[order], s[order]
    m = len(g_sorted)
    first_of_group = np.r_[True, g_sorted[1:] != g_sorted[:-1]]
    group_start = np.maximum.accumulate(np.where(first_of_group, np.arange(m), 0))
    position = np.arange(m) - group_start + 1.0
    new_run = np.r_[True, (g_sorted[1:] != g_sorted[:-1]) | (s_sorted[1:] != s_sorted[:-1])]
    run_id = np.cumsum(new_run) - 1
    run_len = np.bincount(run_id).astype(np.float64)
    run_mean = np.bincount(run_id, weights=position) / run_len
    midrank_sorted = run_mean[run_id]
    midrank = np.empty(m)
    midrank[order] = midrank_sorted
    run_group = g_sorted[new_run]
    ties = np.bincount(run_group, weights=run_len ** 3 - run_len, minlength=n_groups)
    rank_sum = np.bincount(g, weights=midrank * y, minlength=n_groups)
    n2, n = n_pos, n_all
    u = rank_sum - n2 * (n2 + 1) / 2.0
    pairs = n2 * (n - n2)
    with np.errstate(divide="ignore", invalid="ignore"):
        var = np.where(mixed, pairs / 12.0 * ((n + 1) - ties / (n * (n - 1))), 0.0)
    return {"u": u[mixed], "pairs": pairs[mixed], "var": var[mixed],
            "gid": np.searchsorted(np.flatnonzero(mixed), g), "midrank": midrank, "y": y,
            "row_mask": keep}


def within_summary(parts: dict, seed: int = 0) -> dict:
    """AUC, z, one-sided p and a bootstrap interval over conductors."""
    u, pairs, var = parts["u"], parts["pairs"], parts["var"]
    total_pairs = pairs.sum()
    if total_pairs == 0:
        raise HarnessError("no conductor has both a rank-0 and a rank-2 class")
    auc = u.sum() / total_pairs
    z = (u.sum() - total_pairs / 2.0) / math.sqrt(var.sum()) if var.sum() > 0 else 0.0
    rng = np.random.default_rng(seed)
    G = len(u)
    boots = np.empty(BOOTSTRAP_DRAWS)
    for b in range(BOOTSTRAP_DRAWS):
        pick = rng.integers(0, G, G)
        boots[b] = u[pick].sum() / pairs[pick].sum()
    return {"auc_within": round(float(auc), 6), "ci95_low": round(float(np.percentile(boots, 2.5)), 6),
            "ci95_high": round(float(np.percentile(boots, 97.5)), 6), "z": round(float(z), 3),
            "p_one_sided": float(f"{0.5 * math.erfc(z / math.sqrt(2)):.3g}"),
            "pairs": int(total_pairs), "conductors": int(G)}


def paired_delta(parts_a: dict, parts_b: dict, seed: int = 0) -> dict:
    """AUC(a) - AUC(b) on the same rows, with a paired bootstrap over conductors."""
    if len(parts_a["u"]) != len(parts_b["u"]) or not np.array_equal(parts_a["pairs"], parts_b["pairs"]):
        raise HarnessError("paired comparison needs the same rows")
    du = parts_a["u"] - parts_b["u"]
    pairs = parts_a["pairs"]
    rng = np.random.default_rng(seed)
    G = len(du)
    boots = np.empty(BOOTSTRAP_DRAWS)
    for b in range(BOOTSTRAP_DRAWS):
        pick = rng.integers(0, G, G)
        boots[b] = du[pick].sum() / pairs[pick].sum()
    return {"delta_vs_best": round(float(du.sum() / pairs.sum()), 6),
            "delta_ci95_low": round(float(np.percentile(boots, 2.5)), 6),
            "delta_ci95_high": round(float(np.percentile(boots, 97.5)), 6)}


def permutation_p(parts: dict, draws: int = PERMUTATIONS, seed: int = 0) -> float:
    """Monte Carlo p-value: shuffle the rank labels within each conductor."""
    gid, midrank, y = parts["gid"], parts["midrank"], parts["y"].astype(np.float64)
    observed = float((midrank * y).sum())
    order = np.argsort(gid, kind="stable")
    g_sorted, y_sorted, m_sorted = gid[order], y[order], midrank[order]
    rng = np.random.default_rng(seed)
    hits = 0
    for _ in range(draws):
        perm = np.lexsort((rng.random(len(g_sorted)), g_sorted))
        hits += float((m_sorted[perm] * y_sorted).sum()) >= observed - 1e-9
    return round((hits + 1) / (draws + 1), 6)


# ---------------------------------------------------------------- static check
def docstring_nodes(tree: ast.AST) -> set[int]:
    """ids of the Constant nodes that are docstrings."""
    found = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            body = getattr(node, "body", [])
            if (body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant)
                    and isinstance(body[0].value.value, str)):
                found.add(id(body[0].value))
    return found


def module_allowed(name: str) -> bool:
    """True for an allowed top-level module or one of its allowlisted submodules."""
    parts = name.split(".")
    if parts[0] not in ALLOWED_IMPORTS:
        return False
    if len(parts) == 1:
        return True
    return len(parts) == 2 and parts[1] in ALLOWED_SUBMODULES.get(parts[0], frozenset())


def static_check_source(raw: bytes) -> list[str]:
    """Return the reasons an experiment's source is refused (empty if it is fine).

    An allowlist, read from the parsed code: only the listed modules and
    submodules may be imported; nothing that opens files, inspects the
    interpreter or reaches around the harness may be named, as a bare name
    or as an attribute; attribute names may not start with an underscore;
    no string may contain a double underscore; and the file may not carry
    large tables of numbers or text (which could smuggle in labels).
    """
    problems: list[str] = []
    if len(raw) > MAX_EXPERIMENT_BYTES:
        problems.append(f"file is {len(raw)} bytes (limit {MAX_EXPERIMENT_BYTES})")
    try:
        tree = ast.parse(raw.decode("utf-8"))
    except (SyntaxError, UnicodeDecodeError, ValueError) as exc:
        return problems + [f"does not parse: {exc}"]
    docs = docstring_nodes(tree)
    banned_words = BANNED_NAMES | BANNED_ATTRIBUTES
    numbers = 0
    string_chars = 0
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if not module_allowed(alias.name):
                    problems.append(f"import {alias.name}")
        elif isinstance(node, ast.ImportFrom):
            if node.level or not module_allowed(node.module or ""):
                problems.append(f"from {'.' * node.level}{node.module or ''} import")
            for alias in node.names:
                if alias.name == "*":
                    problems.append("import *")
                elif alias.name in banned_words or alias.name.startswith("_"):
                    problems.append(f"import of {alias.name}")
        elif isinstance(node, ast.Name):
            if node.id in banned_words or (node.id.startswith("__") and node.id != "__name__"):
                problems.append(f"name {node.id}")
        elif isinstance(node, ast.Attribute):
            if node.attr in BANNED_ATTRIBUTES or node.attr.startswith("_"):
                problems.append(f"attribute .{node.attr}")
        elif isinstance(node, (ast.List, ast.Tuple, ast.Set)):
            if len(node.elts) > MAX_LITERAL_ELEMENTS:
                problems.append(f"a literal with {len(node.elts)} elements (limit {MAX_LITERAL_ELEMENTS})")
        elif isinstance(node, ast.Dict):
            if len(node.keys) > MAX_LITERAL_ELEMENTS:
                problems.append(f"a dict literal with {len(node.keys)} entries (limit {MAX_LITERAL_ELEMENTS})")
        elif isinstance(node, ast.Constant):
            value = node.value
            if isinstance(value, (int, float, complex)) and not isinstance(value, bool):
                numbers += 1
                if isinstance(value, int) and abs(value) > MAX_INT_MAGNITUDE:
                    problems.append("an integer constant larger than 2**63")
            elif isinstance(value, bytes):
                problems.append("a bytes constant")
            elif isinstance(value, str) and id(node) not in docs:
                string_chars += len(value)
                if len(value) > MAX_STRING_CONSTANT:
                    problems.append(f"a string constant of {len(value)} characters (limit {MAX_STRING_CONSTANT})")
                if "__" in value:
                    problems.append("a string containing a double underscore")
    if numbers > MAX_NUMERIC_CONSTANTS:
        problems.append(f"{numbers} numeric constants (limit {MAX_NUMERIC_CONSTANTS})")
    if string_chars > MAX_STRING_CHARS:
        problems.append(f"{string_chars} characters of string constants (limit {MAX_STRING_CHARS})")
    return sorted(set(problems))


