def cmd_recheck(args: argparse.Namespace) -> int:
    """Re-run an evaluated file on val with seeds 1 and 2, for the Skeptic."""
    path = Path(args.experiment).resolve()
    source = refuse_if_bad(path, "recheck", "val", list(RECHECK_SEEDS), args.note or "")
    sha = hashlib.sha256(source).hexdigest()[:12]
    if not any(r["kind"] == "experiment" and r["split"] == "val" and r["status"] == "ok"
               and r["experiment_sha12"] == sha for r in read_ledger()):
        raise HarnessError("Recheck only a file that `evaluate` has already scored (same contents).")
    rows = []
    for seed in RECHECK_SEEDS:
        if started("recheck") >= RECHECK_BUDGET:
            raise HarnessError(f"The recheck budget of {RECHECK_BUDGET} is used up.")
        row, _, _ = evaluate(path, "recheck", "val", "train", seed, args.note or "",
                             budget=RECHECK_BUDGET, source=source)
        rows.append(row)
    summary = {"experiment": relative(path), "experiment_sha12": sha,
               "seeds": list(RECHECK_SEEDS),
               "auc_within_by_seed": [r["auc_within"] for r in rows],
               "mean_auc_within": round(float(np.mean([r["auc_within"] for r in rows])), 6),
               "delta_vs_best_by_seed": [r.get("delta_vs_best") for r in rows],
               "rechecks_used": started("recheck")}
    print("RECHECK " + json.dumps(summary))
    return 0


def cmd_final(args: argparse.Namespace) -> int:
    path = Path(args.experiment).resolve()
    if path != DEFAULT_EXPERIMENT.resolve():
        raise HarnessError("`final` scores lab/langlands/experiment.py, the promoted experiment, and nothing else.")
    source = refuse_if_bad(path, "final", "test", [SEED], args.note or "")
    check_data()
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    if final_done():
        raise HarnessError(f"The test split was already used ({relative(FINAL_STARTED)}). The final "
                           "result is reported once; it is never re-run to get a better number.")
    result: dict[str, object] = {"fingerprint": fingerprint(),
                                 "experiment_sha256": hashlib.sha256(source).hexdigest(),
                                 "definitions": {"alpha_one_sided": ALPHA, "seed": SEED,
                                                 "bootstrap_draws": BOOTSTRAP_DRAWS,
                                                 "permutations": PERMUTATIONS,
                                                 "test_conductors": [VAL_MAX_N, TEST_MAX_N]}}
    # Part A never reads the test split, so it runs before the split is marked as used.
    print("Part A: murmurations on the confirmatory ranges ...", flush=True)
    result["part_A"] = murmuration_study(Q_CONFIRM, K_CONFIRM)
    (RUNS_DIR / "final_part_A.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result["part_A"]), flush=True)
    try:
        # Created before Part B runs: an interrupted Part B still counts as used.
        with open(FINAL_STARTED, "x", encoding="utf-8") as handle:
            handle.write(json.dumps({"utc": datetime.now(timezone.utc).isoformat(),
                                     "experiment_sha256": hashlib.sha256(source).hexdigest()}) + "\n")
    except FileExistsError:
        raise HarnessError(f"The test split was already used ({relative(FINAL_STARTED)}).") from None
    print("Part B: training experiment.py on train + val, scoring test ...", flush=True)
    table = RankTable()
    fit_idx = np.flatnonzero(table.N < VAL_MAX_N)
    test_idx = table.split("test")
    y = table.rank[test_idx] == 2
    with eval_lock():
        row = base_row("final", "test", relative(path), hashlib.sha256(source).hexdigest()[:12], [SEED],
                       args.note or "final")
        append_ledger({**row, "status": "started"})
        try:
            scores, seconds, cpu = score_split(source, table, fit_idx, test_idx, SEED)
        except HarnessError as exc:
            row.update(status="invalid", note=f"{row['note']} | {exc}"[:500])
            append_ledger(row)
            raise
        exp_parts = within_parts(scores, table.N[test_idx], y)
        row.update(within_summary(exp_parts), seconds=seconds, cpu_seconds=cpu, status="ok")
        append_ledger(row)
        save_details(row, scores, source)
    exp = {k: row[k] for k in ("auc_within", "ci95_low", "ci95_high", "z", "p_one_sided", "pairs",
                               "conductors")}
    exp["permutation_p"] = permutation_p(exp_parts)
    rule_row, rule_parts = frozen_rule_row("split_count", "test", split_count_scores(table, test_idx),
                                           table, test_idx, "final: simple rule")
    ctrl_row, _ = frozen_rule_row("nagao_ap25", "test", nagao_scores(table, test_idx), table, test_idx,
                                  "final: positive control")
    with eval_lock():
        append_ledger(rule_row)
        append_ledger(ctrl_row)
    rule = {k: rule_row[k] for k in exp if k in rule_row}
    rule["permutation_p"] = permutation_p(rule_parts)
    control = {k: ctrl_row[k] for k in ("auc_within", "ci95_low", "ci95_high", "z", "pairs")}
    result["part_B"] = {
        "test_classes": int(len(test_idx)), "test_rank2": int(y.sum()),
        "H_B1_simple_rule": {**rule, "supported": bool(rule["p_one_sided"] < ALPHA
                                                       and rule["permutation_p"] < ALPHA)},
        "H_B2_experiment": {**exp, "supported": bool(exp["p_one_sided"] < ALPHA
                                                     and exp["permutation_p"] < ALPHA)},
        "experiment_minus_simple_rule": {k.replace("delta_vs_best", "delta").replace("delta_ci", "ci"): v
                                         for k, v in paired_delta(exp_parts, rule_parts).items()},
        "positive_control_nagao_ap25": control,
    }
    FINAL_RESULT.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print("FINAL " + json.dumps(result))
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Artemis Langlands harness (frozen).")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("fingerprint", help="SHA-256 of harness, runner and data")
    sub.add_parser("describe", help="the questions, splits and budgets")
    sub.add_parser("baselines", help="score the simple rule and the positive control on val")
    sub.add_parser("murmurations", help="C1 and C2 on the pilot ranges (free)")
    p = sub.add_parser("probe", help="free check inside train (fit N < 200,000, score 200,000-300,000)")
    p.add_argument("--experiment", default=str(DEFAULT_EXPERIMENT))
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--note", default="")
    p = sub.add_parser("evaluate", help="score one experiment on val (counts toward the budget)")
    p.add_argument("--experiment", default=str(DEFAULT_EXPERIMENT))
    p.add_argument("--note", default="")
    p = sub.add_parser("recheck", help="re-run an evaluated file on val with seeds 1 and 2 (Skeptic)")
    p.add_argument("--experiment", default=str(DEFAULT_EXPERIMENT))
    p.add_argument("--note", default="")
    p = sub.add_parser("final", help="Part A confirmatory ranges and Part B test, once")
    p.add_argument("--experiment", default=str(DEFAULT_EXPERIMENT))
    p.add_argument("--note", default="")
    args = parser.parse_args(argv)
    handlers = {"fingerprint": cmd_fingerprint, "describe": cmd_describe, "baselines": cmd_baselines,
                "murmurations": cmd_murmurations, "probe": cmd_probe, "evaluate": cmd_evaluate,
                "recheck": cmd_recheck, "final": cmd_final}
