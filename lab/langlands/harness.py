# ---------------------------------------------------------------- running an experiment
def children_cpu() -> float:
    """CPU seconds used so far by finished child processes (0 where unmeasurable)."""
    if resource is None:
        return 0.0
    usage = resource.getrusage(resource.RUSAGE_CHILDREN)
    return usage.ru_utime + usage.ru_stime


def kill_group(proc: subprocess.Popen) -> None:
    """Kill the runner and anything it started."""
    try:
        if os.name == "posix":
            os.killpg(proc.pid, signal.SIGKILL)
        else:  # pragma: no cover - Windows
            proc.kill()
    except (ProcessLookupError, PermissionError, OSError):
        pass
    try:
        proc.wait(10)
    except subprocess.TimeoutExpired:  # pragma: no cover
        pass


def wait_for(lines: queue.Queue, kind_wanted: str, timeout: float, stderr):
    """Wait for one protocol line; explain anything else."""
    end = time.monotonic() + timeout
    while True:
        remaining = end - time.monotonic()
        if remaining <= 0:
            raise HarnessError(f"no {kind_wanted.lower()} within {timeout:.0f} s; the run was stopped.")
        try:
            stamp, kind, payload = lines.get(timeout=remaining)
        except queue.Empty:
            continue
        if kind == kind_wanted:
            return stamp, payload
        if kind == "ERROR":
            try:
                detail = json.loads(payload)
            except ValueError:
                detail = payload
            raise HarnessError(f"score() raised an error:\n{detail}")
        if kind == "EOF":
            stderr.seek(0)
            tail = stderr.read()[-1500:].decode("utf-8", "replace")
            raise HarnessError(f"the experiment process ended without an answer.\n{tail}")


def runner_env() -> dict[str, str]:
    """A minimal environment for the experiment's process (no keys or tokens)."""
    env = {"OMP_NUM_THREADS": "1", "OPENBLAS_NUM_THREADS": "1", "MKL_NUM_THREADS": "1",
           "NUMEXPR_NUM_THREADS": "1", "PYTHONHASHSEED": "0", "LOKY_MAX_CPU_COUNT": "1"}
    for name in ("PATH", "SYSTEMROOT", "WINDIR", "TEMP", "TMP", "TMPDIR", "LANG", "LC_ALL"):
        if name in os.environ:
            env[name] = os.environ[name]
    return env


def run_experiment(source: bytes, train: list[dict], rows: list[dict], seed: int) -> tuple[np.ndarray, float, float]:
    """Run score(train, rows, seed) from *source* (the exact bytes that were checked and
    hashed) in its own process; return scores, seconds and CPU seconds."""
    token = secrets.token_hex(16)
    message = json.dumps({"token": token, "seed": seed, "train": train, "rows": rows},
                         separators=(",", ":")).encode("utf-8")
    env = runner_env()
    lines: queue.Queue = queue.Queue()
    prefix = token.encode("ascii") + b" "
    with tempfile.TemporaryDirectory() as tmp:
        code_path = Path(tmp) / "experiment_under_test.py"
        code_path.write_bytes(source)
        with open(Path(tmp) / "stderr.txt", "w+b") as stderr:
            cpu_before = children_cpu()
            extra = {"start_new_session": True} if os.name == "posix" else {}
            started_at = time.monotonic()
            proc = subprocess.Popen([sys.executable, "-E", str(RUNNER), str(code_path)],
                                    stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=stderr,
                                    cwd=tmp, env=env, **extra)

            def reader() -> None:
                assert proc.stdout is not None
                for raw in proc.stdout:
                    if raw.startswith(prefix):
                        kind, _, payload = raw[len(prefix):].decode("utf-8", "replace").partition(" ")
                        lines.put((time.monotonic(), kind.strip(), payload))
                lines.put((time.monotonic(), "EOF", ""))

            threading.Thread(target=reader, daemon=True).start()

            def writer() -> None:
                try:
                    assert proc.stdin is not None
                    proc.stdin.write(message)
                    proc.stdin.close()
                except (BrokenPipeError, OSError):
                    pass

            threading.Thread(target=writer, daemon=True).start()
            try:
                ready_at, _ = wait_for(lines, "READY", READY_TIMEOUT_S, stderr)
                done_at, payload = wait_for(lines, "RESULT", TIME_LIMIT_S, stderr)
            finally:
                kill_group(proc)
            cpu = children_cpu() - cpu_before
    wall = done_at - started_at
    if resource is not None and cpu > CPU_FACTOR * wall + CPU_GRACE_S:
        raise HarnessError(f"used {cpu:.0f} CPU seconds in {wall:.0f} s of wall time; experiments "
                           "must use one core.")
    try:
        scores = np.asarray(json.loads(payload), dtype=np.float64)
    except ValueError as exc:
        raise HarnessError(f"the answer could not be read ({exc}).") from exc
    if scores.shape != (len(rows),):
        raise HarnessError(f"score() returned {scores.size} scores for {len(rows)} rows")
    return scores, round(done_at - ready_at, 1), round(cpu, 1)


def score_split(source: bytes, table: RankTable, fit_idx: np.ndarray, eval_idx: np.ndarray,
                seed: int) -> tuple[np.ndarray, float, float]:
    """Train on *fit_idx*, score *eval_idx*; scores come back in file order.

    The data file lists classes in Cremona's class-letter order, which is
    correlated with rank, so that order must never reach an experiment. The
    training rows are handed over sorted by (N, sign pattern, rank), which is
    a function of what each row already shows. The rows to score are handed
    over once per distinct (N, sign pattern), sorted, and every class with
    that pattern receives the same score; classes with the same N and the
    same signs are indistinguishable, so a fair score could not separate
    them anyway. Everything is deterministic: the same code and seed give the
    same numbers on every run.
    """
    train_order = np.lexsort((table.rank[fit_idx], table.mask[fit_idx], table.N[fit_idx]))
    train = table.records(fit_idx[train_order], with_rank=True)
    keys = table.N[eval_idx] * 64 + table.mask[eval_idx]        # at most 6 bad primes below 500,000
    unique_keys, first, inverse = np.unique(keys, return_index=True, return_inverse=True)
    rows = table.records(eval_idx[first], with_rank=False)
    unique_scores, seconds, cpu = run_experiment(source, train, rows, seed)
    return unique_scores[inverse.ravel()], seconds, cpu


@contextlib.contextmanager
def eval_lock():
    """Run one evaluation at a time (memory and CPU); budget checks and ledger writes too."""
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    if fcntl is None:  # Windows: a local check only; the lab itself runs on Linux.
        yield
        return
    with open(LOCK, "w") as handle:
        try:
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            print("Another evaluation is running; waiting for it to finish ...", flush=True)
            fcntl.flock(handle, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)


