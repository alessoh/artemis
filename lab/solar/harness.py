"""Artemis solar harness: the frozen half of the AutoResearch contract.

DO NOT EDIT THIS FILE. Agents edit experiment.py (or a copy of it in trials/);
humans change this file, and every change shows up in its fingerprint.

The question
------------
Among earth-abundant, non-toxic inorganic crystals in NIST JARVIS-DFT, which
ones should we compute next to find excellent solar absorbers fastest?

A visitor to the lab cannot afford the expensive calculation (the TBmBJ optical
spectrum that yields SLME, the spectroscopic limited maximum efficiency) for
every candidate. The experiment therefore sees only cheap properties (the
OptB88vdW band gap, formation energy, energy above the convex hull, composition
and structure) and must put the candidates in the order it would compute them.
The harness then reveals the hidden SLME labels and counts how many expensive
evaluations that order needed to find the target number of excellent absorbers,
compared with picking candidates at random.

Pre-registered definitions (fixed 2026-10-03 by Claude, owner Peter Alesso)
---------------------------------------------------------------------------
Hit:            SLME >= 30.0 % and energy above hull <= 0.1 eV/atom.
Pool:           materials in the chosen split whose every element has a crustal
                abundance >= 1 mg/kg (CRC Handbook, 97th ed.) and which contain
                none of Cd, Hg, Pb, Tl, As, and no radioactive element.
Primary metric: acceleration = (expected evaluations a random order needs to
                find N hits) / (evaluations this order needed), N = 10 or every
                hit in the pool if there are fewer. Higher is better.
Also reported:  hits in the top 25, enrichment in the top 25, average precision.
Splits:         the official JARVIS-Leaderboard SLME split. "train" is known
                (labels visible); "val" is the search pool used in the loop;
                "test" is used exactly once, at the end, by `final`.

The thresholds were chosen after looking only at aggregate counts of SLME
values per split, so that the target is rare enough to make search matter;
no ranking method was tuned before they were fixed.

Commands
--------
    python lab/solar/harness.py fingerprint
    python lab/solar/harness.py describe
    python lab/solar/harness.py baselines
    python lab/solar/harness.py evaluate --experiment lab/solar/trials/NAME.py --note "..."
    python lab/solar/harness.py shortlist -n 15  # never-assessed materials, no labels
    python lab/solar/harness.py final            # once, at the very end
"""

